package hygiene

import (
	"os"
	"path/filepath"
	"regexp"
	"testing"
)

// ciConfigFiles are the files CI installs its tools from.
func ciConfigFiles(t *testing.T) []string {
	t.Helper()
	files := []string{"../../.circleci/config.yml"}
	for _, pattern := range []string{"../../.github/workflows/*.yml", "../../.github/actions/*/action.yml"} {
		matched, err := filepath.Glob(pattern)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, matched...)
	}
	return files
}

// pinnedIn returns the first submatch of every occurrence of pin in the CI files, by file.
func pinnedIn(t *testing.T, pin *regexp.Regexp) map[string][]string {
	t.Helper()
	found := map[string][]string{}
	for _, path := range ciConfigFiles(t) {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		for _, match := range pin.FindAllStringSubmatch(string(raw), -1) {
			found[path] = append(found[path], match[1])
		}
	}
	return found
}

// sourceOfTruth reads the one place a version is declared.
func sourceOfTruth(t *testing.T, path string, declared *regexp.Regexp) string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	match := declared.FindStringSubmatch(string(raw))
	if match == nil {
		t.Fatalf("%s declares no version matching %s", path, declared)
	}
	return match[1]
}

// CI installs a static buf through scripts/ci-install-buf.sh while `make` runs BUF_VERSION,
// and the regenerate-and-diff gates compare the two generators' output.
func TestCIInstallsTheMakefilesBuf(t *testing.T) {
	want := sourceOfTruth(t, "../../Makefile", regexp.MustCompile(`(?m)^BUF_VERSION\s*:=\s*(\S+)\s*$`))
	got := sourceOfTruth(t, "../../scripts/ci-install-buf.sh", regexp.MustCompile(`(?m)^BUF_VERSION=(\S+)\s*$`))
	if got != want {
		t.Errorf("scripts/ci-install-buf.sh installs buf %s; the Makefile's BUF_VERSION is %s", got, want)
	}
	for path, versions := range pinnedIn(t, regexp.MustCompile(`github\.com/bufbuild/buf/releases/download/([^/\s]+)/`)) {
		t.Errorf("%s downloads buf %v itself; scripts/ci-install-buf.sh holds the one pin", path, versions)
	}
}

// The Makefile's default BUF is `go run buf@version`, which resolves buf's module graph
// against the Go checksum database on every run; CI names the installed binary instead.
func TestCIRunsTheInstalledBuf(t *testing.T) {
	bufTarget := regexp.MustCompile(`\b(proto|proto-buf|python-proto|proto-ts|proto-rust|proto-lint|proto-breaking)\b`)
	runs := pinnedIn(t, regexp.MustCompile(`(?m)^\s*(?:-\s+)?(?:run:\s+|command:\s+)?(make\s.*)$`))
	checked := 0
	for path, commands := range runs {
		for _, command := range commands {
			if !bufTarget.MatchString(command) {
				continue
			}
			checked++
			if !regexp.MustCompile(`\sBUF=\S+`).MatchString(command) {
				t.Errorf("%s runs %q without BUF=, so buf is built by `go run`", path, command)
			}
		}
	}
	if checked == 0 {
		t.Fatal("no CI file runs a buf target, so the check would pass over nothing")
	}
}

// The committed Python stubs record the grpcio-tools that generated them, and CI
// regenerates them with the version it installs.
func TestCIInstallsTheGrpcioToolsThatGeneratedThePythonStubs(t *testing.T) {
	want := sourceOfTruth(t, "../../client/python/opensysml/proto/sysml_pb2_grpc.py",
		regexp.MustCompile(`(?m)^GRPC_GENERATED_VERSION\s*=\s*'([^']+)'`))
	found := pinnedIn(t, regexp.MustCompile(`grpcio-tools==([0-9][^\s"']*)`))
	if len(found) == 0 {
		t.Fatal("no CI file installs grpcio-tools, so the check would pass over nothing")
	}
	for path, versions := range found {
		for _, got := range versions {
			if got != want {
				t.Errorf("%s installs grpcio-tools %s; the committed stubs were generated by %s", path, got, want)
			}
		}
	}
}

// The release is built in CircleCI's Go image, which must carry the toolchain
// go.mod pins rather than whichever patch release the minor tag names today.
func TestCircleCIRunsThePinnedToolchain(t *testing.T) {
	want := sourceOfTruth(t, "../../go.mod", regexp.MustCompile(`(?m)^toolchain\s+go(\S+)\s*$`))
	raw, err := os.ReadFile("../../.circleci/config.yml")
	if err != nil {
		t.Fatal(err)
	}
	images := regexp.MustCompile(`(?m)image:\s*cimg/go:([0-9.]+)(?:-\S+)?\s*$`).FindAllStringSubmatch(string(raw), -1)
	if len(images) == 0 {
		t.Fatal(".circleci/config.yml runs no cimg/go image, so the check would pass over nothing")
	}
	for _, image := range images {
		if image[1] != want {
			t.Errorf(".circleci/config.yml runs cimg/go:%s; go.mod pins toolchain go%s", image[1], want)
		}
	}
}
