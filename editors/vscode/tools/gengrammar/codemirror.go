package main

import (
	"bytes"
	"encoding/json"

	"github.com/Open-MBEE/OpenSysML/editors/internal/keywords"
)

// SyntaxTableFile is where the JupyterLab extension's CodeMirror language reads
// its keywords, relative to the extension's directory.
const SyntaxTableFile = "src/syntax.json"

// SyntaxTable is the keyword and operator table the CodeMirror language of
// editors/jupyterlab consumes: the same groups the TextMate grammars are built
// from, keyed by the group's short name, so both editors colour one word alike.
type SyntaxTable struct {
	Comment       string              `json:"comment"`
	Keywords      map[string][]string `json:"keywords"`
	Constants     []string            `json:"constants"`
	Contextual    map[string][]string `json:"contextual"`
	Operators     []string            `json:"operators"`
	OperatorChars string              `json:"operatorChars"`
}

// syntaxTable builds the table from the keyword groups, after the same checks
// repository makes: every grouped word is a keyword, none is grouped twice, and
// no contextual word is reserved.
func syntaxTable() (*SyntaxTable, error) {
	groups, err := keywords.Groups()
	if err != nil {
		return nil, err
	}
	table := &SyntaxTable{
		Comment:       "Generated by editors/vscode/tools/gengrammar from internal/syntax/source.Keywords() and lexer.ContextualWords(); do not edit by hand.",
		Keywords:      map[string][]string{string(keywords.Other): {}},
		Contextual:    map[string][]string{},
		Operators:     append([]string(nil), multiCharOperators...),
		OperatorChars: operatorChars,
	}
	for _, group := range groups {
		if group.Category == keywords.Constant {
			table.Constants = group.Words
			continue
		}
		table.Keywords[string(group.Category)] = group.Words
	}
	for _, g := range Grammars() {
		contextual, err := keywords.Contextual(g.Kind)
		if err != nil {
			return nil, err
		}
		table.Contextual[g.FileTypes[0]] = contextual
	}
	return table, nil
}

// RenderSyntaxTable returns the JSON text of the CodeMirror syntax table,
// ending in a newline.
func RenderSyntaxTable() ([]byte, error) {
	table, err := syntaxTable()
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(table); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
