package main

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"

	"github.com/Open-MBEE/OpenSysML/editors/internal/keywords"
	"github.com/Open-MBEE/OpenSysML/internal/syntax/source"
)

// File is the name of the generated library.
const File = "sysml-mode-keywords.el"

// languages are the modes whose contextual words differ, keyed by the symbol
// sysml-mode looks them up under.
var languages = []struct {
	symbol string
	kind   source.Kind
}{
	{"sysml", source.KindSysML},
	{"kerml", source.KindKerML},
}

// lineWidth is where a list of words wraps.
const lineWidth = 80

// Render returns the text of sysml-mode-keywords.el.
func Render() ([]byte, error) {
	groups, err := keywords.Groups()
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(`;;; sysml-mode-keywords.el --- Keyword lists for sysml-mode  -*- lexical-binding: t; -*-

;; Copyright The OpenSysML Authors
;; SPDX-License-Identifier: Apache-2.0

;;; Commentary:

;; Generated by editors/emacs/tools/genkeywords from
;; internal/syntax/source.Keywords() and lexer.ContextualWords(); do not edit
;; by hand.  Regenerate with ` + "`make emacs-keywords'" + `.

;;; Code:

(defconst sysml-mode-keyword-groups
  '(`)
	for i, g := range groups {
		if i > 0 {
			b.WriteString("\n    ")
		}
		writeList(&b, string(g.Category), g.Words, "    ")
	}
	b.WriteString(`)
  "The lexer's reserved words, grouped by the syntax they introduce.
Each element is (CATEGORY WORD...).  Every reserved word is in exactly
one group.")

(defconst sysml-mode-declaration-introducers
  '(`)
	introducers, err := keywords.Introducers()
	if err != nil {
		return nil, err
	}
	b.WriteString(strings.Join(quoteAll(introducers), " "))
	b.WriteString(`)
  "The reserved words directly followed by the name a declaration introduces.")

(defconst sysml-mode-contextual-words
  '(`)
	for i, lang := range languages {
		words, err := keywords.Contextual(lang.kind)
		if err != nil {
			return nil, err
		}
		if i > 0 {
			b.WriteString("\n    ")
		}
		writeList(&b, lang.symbol, words, "    ")
	}
	b.WriteString(`)
  "The words each language reads as syntax in one position only.
Each element is (LANGUAGE WORD...).  The lexer does not reserve them, so
a model may still use them as names.")

(provide 'sysml-mode-keywords)

;;; sysml-mode-keywords.el ends here
`)
	return b.Bytes(), nil
}

func quoteAll(words []string) []string {
	out := make([]string, len(words))
	for i, w := range words {
		out[i] = strconv.Quote(w)
	}
	return out
}

// writeList writes (HEAD "word" ...), wrapping continuation lines at lineWidth
// with indent before them.
func writeList(b *bytes.Buffer, head string, words []string, indent string) {
	line := "(" + head
	col := len(indent)
	var lines []string
	for _, w := range words {
		q := strconv.Quote(w)
		if col+len(line)+1+len(q) > lineWidth {
			lines = append(lines, line)
			line = " " + q
			continue
		}
		line += " " + q
	}
	lines = append(lines, line+")")
	fmt.Fprint(b, strings.Join(lines, "\n"+indent))
}
