// Command pymetamodel writes the generated Python view of the SysML metamodel.
//
//	go run -C tools ./gen/pymetamodel [-check]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/Open-MBEE/OpenSysML/internal/translate/rdf/ontology"
	"github.com/Open-MBEE/OpenSysML/tools/oracle/repo"
)

const (
	outputPath = "client/python/opensysml/metamodel/_generated.py"
	regenerate = "make python-metamodel"
	sysmlNS    = "https://www.omg.org/spec/SysML#"
	xsdNS      = "http://www.w3.org/2001/XMLSchema#"
	owlNS      = "http://www.w3.org/2002/07/owl#"
)

var runtimeMembers = []string{
	"METACLASS", "JSON_KEYS", "from_json_key", "json_key", "json_id",
	"json_type", "json_value", "graph", "metaclass_name",
}

var pythonKeywords = keywordSet(
	"False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield",
)

func main() {
	out := flag.String("out", outputPath, "generated Python module (default "+outputPath+")")
	check := flag.Bool("check", false, "fail if the generated module differs from the output")
	flag.Parse()
	root, err := repo.Root()
	if err != nil {
		fail(err)
	}
	*out = repo.Resolve(root, *out)
	if *out == "" {
		*out = filepath.Join(root, filepath.FromSlash(outputPath))
	}
	data, err := generate(ontology.Classes(), ontology.Properties(), ontology.Enumerations(),
		ontology.Version, ontology.SourceTag, ontology.SourceCommit)
	if err != nil {
		fail(err)
	}
	if *check {
		have, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(have, data) {
			fail(fmt.Errorf("%s is stale; regenerate with `%s`", *out, regenerate))
		}
		fmt.Printf("%s is current: %d classes, %d properties, %d enumerations (metamodel %s, pilot %s)\n",
			*out, len(ontology.Classes()), len(ontology.Properties()), len(ontology.Enumerations()),
			ontology.Version, ontology.SourceTag)
		return
	}
	if err := os.WriteFile(*out, data, 0o600); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s: %d classes, %d properties, %d enumerations (metamodel %s, pilot %s)\n",
		*out, len(ontology.Classes()), len(ontology.Properties()), len(ontology.Enumerations()),
		ontology.Version, ontology.SourceTag)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "pymetamodel:", err)
	os.Exit(1)
}

type model struct {
	classes    []ontology.Class
	properties []ontology.Property
	enums      []ontology.Enumeration
	classBy    map[string]ontology.Class
	enumBy     map[string]ontology.Enumeration
	mros       map[string][]string
	effective  map[string]map[string]ontology.Property
}

func generate(classes []ontology.Class, properties []ontology.Property, enums []ontology.Enumeration,
	version, tag, commit string) ([]byte, error) {
	m, err := newModel(classes, properties, enums)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# Code generated by tools/gen/pymetamodel. DO NOT EDIT.
# Metamodel: %s
# Pilot tag: %s
# Pilot commit: %s
# Regenerate with: %s

from __future__ import annotations

import builtins
from enum import Enum
from types import MappingProxyType
from typing import ClassVar, Mapping

from ._runtime import Many, Opt, _ElementBase  # pyright: ignore[reportPrivateUsage]

METAMODEL_VERSION = %q
SOURCE_TAG = %q
SOURCE_COMMIT = %q

`, version, tag, commit, regenerate, version, tag, commit)

	for _, enum := range m.enums {
		fmt.Fprintf(&b, "class %s(str, Enum):\n", enum.Name)
		for _, literal := range enum.Literals {
			fmt.Fprintf(&b, "    %s = %q\n", strings.ToUpper(literal), literal)
		}
		b.WriteString("\n\n")
	}

	for _, class := range m.classes {
		if class.Name == "Element" {
			fmt.Fprintf(&b, "class Element(_ElementBase):\n")
		} else if len(class.Parents) == 0 {
			fmt.Fprintf(&b, "class %s:\n", class.Name)
		} else {
			fmt.Fprintf(&b, "class %s(%s):\n", class.Name, strings.Join(class.Parents, ", "))
		}
		doc := "Metaclass ``" + class.Name + "``."
		if class.Abstract {
			doc = "Abstract metaclass ``" + class.Name + "``."
		}
		fmt.Fprintf(&b, "    %q\n    __slots__ = ()\n", doc)
		fmt.Fprintf(&b, "    METACLASS: ClassVar[str] = %q\n", class.Name)
		writeJSONKeys(&b, class, m)
		for _, property := range m.declaredProperties(class.Name) {
			snake := toSnake(property.Name)
			rangeAnnotation, rangeName, err := m.pythonRange(property)
			if err != nil {
				return nil, err
			}
			descriptor := "Opt"
			if property.Many {
				descriptor = "Many"
			}
			fmt.Fprintf(&b, "    %s: %s[%s] = %s(%q, %q",
				snake, descriptor, rangeAnnotation, descriptor, property.Name, rangeName)
			if property.Many {
				fmt.Fprintf(&b, ", ordered=%s", pythonBool(property.Ordered))
			}
			if property.Derived {
				b.WriteString(", derived=True")
			}
			b.WriteString(")\n")
			parts := []string{"single"}
			if property.Many {
				parts = []string{"many"}
				if property.Ordered {
					parts = append(parts, "ordered")
				}
			}
			if property.Derived {
				parts = append(parts, "derived")
			}
			doc := fmt.Sprintf("``%s::%s`` (%s).", class.Name, property.Name, strings.Join(parts, ", "))
			if len(property.Redefines) > 0 {
				targets := make([]string, len(property.Redefines))
				for i, redefined := range property.Redefines {
					targets[i] = "``" + redefined + "``"
				}
				doc += " Redefines " + strings.Join(targets, ", ") + "."
			}
			fmt.Fprintf(&b, "    %q\n", doc)
			if property.Name != snake && !pythonKeywords[property.Name] {
				fmt.Fprintf(&b, "    %s = %s\n", property.Name, snake)
			}
		}
		b.WriteString("\n\n")
	}

	b.WriteString("REGISTRY: Mapping[str, builtins.type[Element]] = MappingProxyType({\n")
	for _, class := range m.classes {
		fmt.Fprintf(&b, "    %q: %s,\n", class.Name, class.Name)
	}
	b.WriteString("})\n\n")
	b.WriteString("ENUMERATIONS: Mapping[str, builtins.type[Enum]] = MappingProxyType({\n")
	for _, enum := range m.enums {
		fmt.Fprintf(&b, "    %q: %s,\n", enum.Name, enum.Name)
	}
	b.WriteString("})\n\nRUNTIME_MEMBERS = frozenset({\n")
	for _, name := range runtimeMembers {
		fmt.Fprintf(&b, "    %q,\n", name)
	}
	b.WriteString("})\n\n__all__ = [\n")
	names := make([]string, 0, len(m.classes)+len(m.enums)+7)
	for _, class := range m.classes {
		names = append(names, class.Name)
	}
	for _, enum := range m.enums {
		names = append(names, enum.Name)
	}
	names = append(names, "ENUMERATIONS", "METAMODEL_VERSION", "REGISTRY", "RUNTIME_MEMBERS",
		"SOURCE_COMMIT", "SOURCE_TAG")
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(&b, "    %q,\n", name)
	}
	b.WriteString("]\n")
	return []byte(b.String()), nil
}

func newModel(classes []ontology.Class, properties []ontology.Property,
	enums []ontology.Enumeration) (*model, error) {
	m := &model{
		classes: classes, properties: properties, enums: enums,
		classBy:   make(map[string]ontology.Class, len(classes)),
		enumBy:    make(map[string]ontology.Enumeration, len(enums)),
		mros:      make(map[string][]string, len(classes)),
		effective: make(map[string]map[string]ontology.Property, len(classes)),
	}
	for _, class := range classes {
		if class.Name == "" {
			return nil, fmt.Errorf("metaclass without a name")
		}
		if _, duplicate := m.classBy[class.Name]; duplicate {
			return nil, fmt.Errorf("metaclass %s is declared more than once", class.Name)
		}
		m.classBy[class.Name] = class
	}
	if _, ok := m.classBy["Element"]; !ok {
		return nil, fmt.Errorf("metaclass Element is not declared")
	}
	for _, enum := range enums {
		if enum.Name == "" || len(enum.Literals) == 0 {
			return nil, fmt.Errorf("enumeration %q has no literals", enum.Name)
		}
		if _, duplicate := m.enumBy[enum.Name]; duplicate {
			return nil, fmt.Errorf("enumeration %s is declared more than once", enum.Name)
		}
		m.enumBy[enum.Name] = enum
	}
	for name := range m.enumBy {
		if _, exists := m.classBy[name]; exists {
			return nil, fmt.Errorf("metaclass and enumeration share generated name %s", name)
		}
		if contains([]string{"METAMODEL_VERSION", "SOURCE_TAG", "SOURCE_COMMIT", "REGISTRY",
			"ENUMERATIONS", "RUNTIME_MEMBERS"}, name) {
			return nil, fmt.Errorf("enumeration %s collides with a generated module member", name)
		}
	}
	for _, property := range properties {
		if _, ok := m.classBy[property.DefiningClass]; !ok {
			return nil, fmt.Errorf("%s::%s has no declaring metaclass", property.DefiningClass, property.Name)
		}
	}
	order, err := m.topologicalOrder()
	if err != nil {
		return nil, err
	}
	m.classes = order
	for _, class := range m.classes {
		if _, err := m.linearize(class.Name, map[string]bool{}); err != nil {
			return nil, err
		}
	}
	if err := m.validateDeclarations(); err != nil {
		return nil, err
	}
	for _, class := range m.classes {
		effective := make(map[string]ontology.Property)
		for _, ancestor := range m.mros[class.Name] {
			for _, property := range m.properties {
				if property.DefiningClass == ancestor {
					if _, exists := effective[property.Name]; !exists {
						effective[property.Name] = property
					}
				}
			}
		}
		m.effective[class.Name] = effective
		if err := m.validateEffective(class.Name, effective); err != nil {
			return nil, err
		}
	}
	for _, property := range properties {
		if _, _, err := m.pythonRange(property); err != nil {
			return nil, err
		}
	}
	return m, nil
}

func (m *model) validateDeclarations() error {
	declared := make(map[string][]string)
	for _, property := range m.properties {
		names := declared[property.Name]
		for _, previous := range names {
			if m.ancestor(property.DefiningClass, previous) || m.ancestor(previous, property.DefiningClass) {
				return fmt.Errorf("property %s is declared by related metaclasses %s and %s",
					property.Name, previous, property.DefiningClass)
			}
		}
		declared[property.Name] = append(names, property.DefiningClass)
		snake, camel := toSnake(property.Name), property.Name
		for _, name := range []string{snake, camel} {
			if contains(runtimeMembers, name) {
				return fmt.Errorf("property %s on %s collides with runtime member %s", property.Name, property.DefiningClass, name)
			}
			if m.classBy[name].Name != "" || m.enumBy[name].Name != "" ||
				contains([]string{"Opt", "Many", "ClassVar", "Mapping", "MappingProxyType",
					"builtins", "str", "bool", "int", "float"}, name) {
				return fmt.Errorf("property %s on %s shadows generated class-body name %s", property.Name, property.DefiningClass, name)
			}
		}
		if !pythonIdentifier(snake) {
			return fmt.Errorf("property %q has no valid Python name", property.Name)
		}
	}
	for _, enum := range m.enums {
		literalNames := map[string]bool{}
		for _, literal := range enum.Literals {
			member := strings.ToUpper(literal)
			if !pythonIdentifier(member) || pythonKeywords[member] {
				return fmt.Errorf("enum literal %q in %s does not produce a valid Python identifier", literal, enum.Name)
			}
			if literalNames[member] {
				return fmt.Errorf("enum %s has duplicate Python member %s", enum.Name, member)
			}
			literalNames[member] = true
		}
	}
	return nil
}

func (m *model) validateEffective(class string, effective map[string]ontology.Property) error {
	names := make(map[string]string, len(effective))
	for key := range effective {
		snake := toSnake(key)
		if previous, exists := names[snake]; exists {
			return fmt.Errorf("%s has property keys %s and %s with the same Python name %s",
				class, previous, key, snake)
		}
		names[snake] = key
	}
	return nil
}

func (m *model) topologicalOrder() ([]ontology.Class, error) {
	children := make(map[string][]string, len(m.classes))
	remaining := make(map[string]int, len(m.classes))
	for _, class := range m.classes {
		remaining[class.Name] = len(class.Parents)
		for _, parent := range class.Parents {
			if _, ok := m.classBy[parent]; !ok {
				return nil, fmt.Errorf("%s has unknown metaclass parent %s", class.Name, parent)
			}
			children[parent] = append(children[parent], class.Name)
		}
	}
	var ready []string
	for name, count := range remaining {
		if count == 0 {
			ready = append(ready, name)
		}
	}
	sort.Strings(ready)
	order := make([]ontology.Class, 0, len(m.classes))
	for len(ready) > 0 {
		name := ready[0]
		ready = ready[1:]
		order = append(order, m.classBy[name])
		for _, child := range children[name] {
			remaining[child]--
			if remaining[child] == 0 {
				ready = append(ready, child)
			}
		}
		sort.Strings(ready)
	}
	if len(order) != len(m.classes) {
		return nil, fmt.Errorf("metaclass inheritance contains a cycle")
	}
	return order, nil
}

func (m *model) linearize(name string, visiting map[string]bool) ([]string, error) {
	if mro, ok := m.mros[name]; ok {
		return mro, nil
	}
	if visiting[name] {
		return nil, fmt.Errorf("C3 linearization failed for %s: inheritance cycle", name)
	}
	visiting[name] = true
	class := m.classBy[name]
	sequences := make([][]string, 0, len(class.Parents)+1)
	for _, parent := range class.Parents {
		parentMRO, err := m.linearize(parent, visiting)
		if err != nil {
			return nil, err
		}
		sequences = append(sequences, append([]string(nil), parentMRO...))
	}
	sequences = append(sequences, append([]string(nil), class.Parents...))
	result := []string{name}
	for {
		active := sequences[:0]
		for _, sequence := range sequences {
			if len(sequence) != 0 {
				active = append(active, sequence)
			}
		}
		sequences = active
		if len(sequences) == 0 {
			break
		}
		var candidate string
		for _, sequence := range sequences {
			head := sequence[0]
			inTail := false
			for _, other := range sequences {
				for _, tail := range other[1:] {
					if tail == head {
						inTail = true
						break
					}
				}
				if inTail {
					break
				}
			}
			if !inTail {
				candidate = head
				break
			}
		}
		if candidate == "" {
			return nil, fmt.Errorf("C3 linearization failed for %s: inconsistent parents %v", name, class.Parents)
		}
		result = append(result, candidate)
		for i, sequence := range sequences {
			if sequence[0] == candidate {
				sequences[i] = sequence[1:]
			}
		}
	}
	delete(visiting, name)
	m.mros[name] = result
	return result, nil
}

func (m *model) ancestor(class, ancestor string) bool {
	for _, name := range m.mros[class] {
		if name == ancestor {
			return true
		}
	}
	return false
}

func (m *model) declaredProperties(class string) []ontology.Property {
	var out []ontology.Property
	for _, property := range m.properties {
		if property.DefiningClass == class {
			out = append(out, property)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func (m *model) pythonRange(property ontology.Property) (annotation, name string, err error) {
	switch property.Range {
	case xsdNS + "boolean":
		return "bool", "bool", nil
	case xsdNS + "string":
		return "str", "str", nil
	case xsdNS + "int":
		return "int", "int", nil
	case owlNS + "real":
		return "float", "float", nil
	}
	if local, ok := strings.CutPrefix(property.Range, sysmlNS); ok {
		if _, exists := m.classBy[local]; exists && property.Kind == ontology.ObjectProperty {
			return local, local, nil
		}
		if _, exists := m.enumBy[local]; exists && property.Kind == ontology.DatatypeProperty {
			return local, local, nil
		}
	}
	return "", "", fmt.Errorf("%s::%s has unsupported range %q", property.DefiningClass, property.Name, property.Range)
}

func writeJSONKeys(b *strings.Builder, class ontology.Class, m *model) {
	b.WriteString("    JSON_KEYS: ClassVar[Mapping[str, str]] = MappingProxyType({\n")
	if class.Name == "Element" {
		b.WriteString("        **_ElementBase.JSON_KEYS,\n")
	} else {
		for i := len(class.Parents) - 1; i >= 0; i-- {
			fmt.Fprintf(b, "        **%s.JSON_KEYS,\n", class.Parents[i])
		}
	}
	for _, property := range m.declaredProperties(class.Name) {
		fmt.Fprintf(b, "        %q: %q,\n", property.Name, toSnake(property.Name))
	}
	b.WriteString("    })\n")
}

func toSnake(name string) string {
	runes := []rune(name)
	var b strings.Builder
	for i, current := range runes {
		if i > 0 && unicode.IsUpper(current) {
			previous := runes[i-1]
			nextIsLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
			if unicode.IsLower(previous) || unicode.IsDigit(previous) ||
				(unicode.IsUpper(previous) && nextIsLower) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToLower(current))
	}
	snake := b.String()
	if pythonKeywords[snake] {
		return snake + "_"
	}
	return snake
}

func pythonIdentifier(name string) bool {
	for i, r := range name {
		if i == 0 {
			if r != '_' && !unicode.IsLetter(r) {
				return false
			}
		} else if r != '_' && !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			return false
		}
	}
	return name != ""
}

func pythonBool(value bool) string {
	if value {
		return "True"
	}
	return "False"
}

func keywordSet(words string) map[string]bool {
	out := make(map[string]bool)
	for _, word := range strings.Fields(words) {
		out[word] = true
	}
	return out
}

func contains(values []string, value string) bool {
	for _, candidate := range values {
		if candidate == value {
			return true
		}
	}
	return false
}
