// Command ontology writes internal/translate/rdf/ontology/table.go from the OMG
// SysML v2 metamodel's SysML.ecore as the pinned pilot implementation publishes
// it. scripts/download-pilot-metamodel.sh fetches it into build/pilot-metamodel
// at the commit scripts/pilot-pin.sh pins, which the header records.
//
//	./scripts/download-pilot-metamodel.sh
//	go run -C tools ./gen/ontology [-check]
package main

import (
	"bytes"
	"encoding/xml"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/Open-MBEE/OpenSysML/tools/oracle/baseline"
	"github.com/Open-MBEE/OpenSysML/tools/oracle/repo"
)

const (
	// tablePath is the generated table, relative to the repository root.
	tablePath = "internal/translate/rdf/ontology/table.go"
	// metamodelDir is where scripts/download-pilot-metamodel.sh puts the pilot's model directory.
	metamodelDir = "build/pilot-metamodel"
	// ecorePath is the metamodel in that directory and in the pilot repository's org.omg.sysml/model.
	ecorePath = "SysML.ecore"
	stampPath = ".pilot-pin"
	sysmlNS   = "https://www.omg.org/spec/SysML#"
	xsdNS     = "http://www.w3.org/2001/XMLSchema#"
	owlNS     = "http://www.w3.org/2002/07/owl#"
	xsiNS     = "http://www.w3.org/2001/XMLSchema-instance"
	regen     = "./scripts/download-pilot-metamodel.sh && go run -C tools ./gen/ontology"
	template  = `// Code generated by tools/gen/ontology. DO NOT EDIT.
//
// Source:    %s %s, org.omg.sysml/model/SysML.ecore
// Commit:    %s
// Metamodel: %s
//
// Regenerate with (see README.md):
//
//	./scripts/download-pilot-metamodel.sh
//	go run -C tools ./gen/ontology

package ontology

// Version is the OMG SysML v2 metamodel version the table was generated from,
// the date in the ecore's namespace URI.
const Version = %q

// SourceTag is the pilot implementation release the table was generated from.
const SourceTag = %q

// SourceCommit is the pilot implementation commit the table was generated from.
const SourceCommit = %q

// properties holds every eStructuralFeature the metamodel declares, ordered by IRI.
var properties = []Property{
%s}

// enumerations holds every EEnum and its literals in declaration order, ordered by name.
var enumerations = []Enumeration{
%s}

// classes holds every EClass the metamodel declares with its eSuperTypes, ordered by name.
var classes = []Class{
%s}
`
)

// datatypeRanges maps an ecore primitive, in the pilot's own spelling and in
// Ecore's, to the XSD or OWL datatype the RDF mapping writes it as.
var datatypeRanges = map[string]string{
	"Boolean": xsdNS + "boolean", "EBoolean": xsdNS + "boolean",
	"String": xsdNS + "string", "EString": xsdNS + "string",
	"Integer": xsdNS + "int", "EInt": xsdNS + "int",
	"Real": owlNS + "real", "EDouble": owlNS + "real",
}

func main() {
	dir := flag.String("metamodel", "", "directory holding the pilot's SysML.ecore and its .pilot-pin stamp (default "+metamodelDir+" under the repository root)")
	out := flag.String("out", "", "generated file to write (default "+tablePath+" under the repository root)")
	check := flag.Bool("check", false, "fail if the file differs from a fresh table instead of writing it")
	flag.Parse()
	root, err := repo.Root()
	if err != nil {
		fail(err)
	}
	pin, err := baseline.ReadPin(root)
	if err != nil {
		fail(err)
	}
	*dir = repo.Resolve(root, *dir)
	if *dir == "" {
		*dir = filepath.Join(root, filepath.FromSlash(metamodelDir))
	}
	*out = repo.Resolve(root, *out)
	if *out == "" {
		*out = filepath.Join(root, filepath.FromSlash(tablePath))
	}
	if err := run(*dir, *out, *check, pin); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "ontology:", err)
	os.Exit(1)
}

// run generates the table from dir and writes it to out, or with check
// compares it against out; the stamp in dir must name pin.
func run(dir, out string, check bool, pin baseline.Pin) error {
	src, err := readStamp(filepath.Join(dir, stampPath))
	if err != nil {
		return err
	}
	if src.tag != pin.Tag || src.commit != pin.Commit {
		return fmt.Errorf("%s holds the metamodel at %s %s, but %s pins %s %s; rerun ./scripts/download-pilot-metamodel.sh",
			dir, src.tag, src.commit, baseline.PinPath, pin.Tag, pin.Commit)
	}
	pkg, err := parseEcore(filepath.Join(dir, ecorePath))
	if err != nil {
		return err
	}
	version, err := metamodelVersion(pkg.NsURI)
	if err != nil {
		return err
	}
	properties, classes, err := tables(pkg)
	if err != nil {
		return fmt.Errorf("%s: %w", ecorePath, err)
	}
	enums, err := enumerationTables(pkg)
	if err != nil {
		return fmt.Errorf("%s: %w", ecorePath, err)
	}
	source := fmt.Sprintf(template, src.repo, src.tag, src.commit, pkg.NsURI, version, src.tag, src.commit,
		propertyLiterals(properties), enumerationLiterals(enums), classLiterals(classes))
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if check {
		// #nosec G304 -- the table to compare is named on the command line.
		have, err := os.ReadFile(out)
		if err != nil || !bytes.Equal(have, formatted) {
			return fmt.Errorf("%s is stale against %s at %s; regenerate with `%s`", out, ecorePath, src.tag, regen)
		}
		fmt.Printf("%s is current: %d properties, %d classes (metamodel %s, pilot %s)\n",
			out, len(properties), len(classes), version, src.tag)
		return nil
	}
	if err := os.WriteFile(out, formatted, 0o600); err != nil {
		return err
	}
	fmt.Printf("wrote %s: %d properties, %d classes (metamodel %s, pilot %s, commit %s)\n",
		out, len(properties), len(classes), version, src.tag, src.commit[:12])
	return nil
}

// source is the provenance a fetched metamodel directory's stamp records.
type source struct{ tag, commit, repo string }

var commitSHAPattern = regexp.MustCompile(`^[0-9a-f]{40}$`)

// readStamp reads the "<tag> <commit> <repository>" stamp pilot_fetch_subtrees writes.
func readStamp(path string) (source, error) {
	// #nosec G304 -- the stamp sits in the metamodel directory named on the command line.
	data, err := os.ReadFile(path)
	if err != nil {
		return source{}, fmt.Errorf("read the metamodel's pin stamp (fetch it with ./scripts/download-pilot-metamodel.sh): %w", err)
	}
	fields := strings.Fields(string(data))
	if len(fields) != 3 || !commitSHAPattern.MatchString(fields[1]) {
		return source{}, fmt.Errorf("%s: want \"<tag> <commit> <repository>\", got %q", path, strings.TrimSpace(string(data)))
	}
	return source{tag: fields[0], commit: fields[1], repo: fields[2]}, nil
}

var nsURIVersion = regexp.MustCompile(`^https://www\.omg\.org/spec/SysML/(\d{8})$`)

// metamodelVersion is the date the ecore's nsURI ends in, the version OMG publishes the metamodel under.
func metamodelVersion(nsURI string) (string, error) {
	match := nsURIVersion.FindStringSubmatch(nsURI)
	if match == nil {
		return "", fmt.Errorf("%s: nsURI %q is not https://www.omg.org/spec/SysML/<yyyymmdd>", ecorePath, nsURI)
	}
	return match[1], nil
}

// ePackage and the types below are the part of the ecore XMI the table reads.
type ePackage struct {
	NsURI       string        `xml:"nsURI,attr"`
	Classifiers []eClassifier `xml:"eClassifiers"`
	Subpackages []struct{}    `xml:"eSubpackages"`
}

type eClassifier struct {
	Type       string     `xml:"http://www.w3.org/2001/XMLSchema-instance type,attr"`
	Name       string     `xml:"name,attr"`
	Abstract   bool       `xml:"abstract,attr"`
	SuperTypes string     `xml:"eSuperTypes,attr"`
	Features   []eFeature `xml:"eStructuralFeatures"`
	Literals   []eLiteral `xml:"eLiterals"`
}

type eLiteral struct {
	Name string `xml:"name,attr"`
}

type eFeature struct {
	Type        string        `xml:"http://www.w3.org/2001/XMLSchema-instance type,attr"`
	Name        string        `xml:"name,attr"`
	EType       string        `xml:"eType,attr"`
	UpperBound  string        `xml:"upperBound,attr"`
	Ordered     string        `xml:"ordered,attr"`
	Derived     bool          `xml:"derived,attr"`
	Opposite    string        `xml:"eOpposite,attr"`
	Annotations []eAnnotation `xml:"eAnnotations"`
}

type eAnnotation struct {
	Source     string `xml:"source,attr"`
	References string `xml:"references,attr"`
}

func parseEcore(path string) (ePackage, error) {
	// #nosec G304 -- the metamodel directory is named on the command line.
	data, err := os.ReadFile(path)
	if err != nil {
		return ePackage{}, err
	}
	var pkg ePackage
	if err := xml.Unmarshal(data, &pkg); err != nil {
		return ePackage{}, fmt.Errorf("%s: %w", path, err)
	}
	if len(pkg.Subpackages) > 0 {
		return ePackage{}, fmt.Errorf("%s: eSubpackages are not supported; the metamodel is one flat package", path)
	}
	if len(pkg.Classifiers) == 0 {
		return ePackage{}, fmt.Errorf("%s: no eClassifiers found", path)
	}
	return pkg, nil
}

// property and class mirror the generated table's types, which cannot be imported:
// the package they live in does not compile until this has run.
type property struct {
	name, definingClass, iri, kind, rangeIRI, opposite string
	many, ordered, derived                             bool
	redefines, subsets                                 []string
}

type class struct {
	name     string
	abstract bool
	parents  []string
}

type enumeration struct {
	name     string
	literals []string
}

func enumerationTables(pkg ePackage) ([]enumeration, error) {
	var enums []enumeration
	for _, classifier := range pkg.Classifiers {
		if classifier.Type != "ecore:EEnum" {
			continue
		}
		if len(classifier.Literals) == 0 {
			return nil, fmt.Errorf("EEnum %s has no literals", classifier.Name)
		}
		enum := enumeration{name: classifier.Name, literals: make([]string, 0, len(classifier.Literals))}
		for _, literal := range classifier.Literals {
			if literal.Name == "" {
				return nil, fmt.Errorf("EEnum %s has a literal without a name", classifier.Name)
			}
			enum.literals = append(enum.literals, literal.Name)
		}
		enums = append(enums, enum)
	}
	sort.Slice(enums, func(i, j int) bool { return enums[i].name < enums[j].name })
	return enums, nil
}

// tables reads the classes and properties out of the package, checking every
// cross-reference resolves inside it.
func tables(pkg ePackage) ([]property, []class, error) {
	kinds := map[string]string{}
	features := map[string]bool{}
	for _, c := range pkg.Classifiers {
		if c.Name == "" {
			return nil, nil, errors.New("eClassifiers without a name")
		}
		if _, dup := kinds[c.Name]; dup {
			return nil, nil, fmt.Errorf("eClassifiers %s declared twice", c.Name)
		}
		kinds[c.Name] = c.Type
		for _, f := range c.Features {
			features[c.Name+"::"+f.Name] = true
		}
	}
	var (
		properties []property
		classes    []class
	)
	for _, c := range pkg.Classifiers {
		if c.Type != "ecore:EClass" {
			if len(c.Features) > 0 {
				return nil, nil, fmt.Errorf("%s: a %s with eStructuralFeatures", c.Name, c.Type)
			}
			continue
		}
		var parents []string
		for _, ref := range strings.Fields(c.SuperTypes) {
			parent, ok := strings.CutPrefix(ref, "#//")
			if !ok || kinds[parent] != "ecore:EClass" {
				return nil, nil, fmt.Errorf("%s: eSuperTypes %s is no EClass of the package", c.Name, ref)
			}
			parents = append(parents, parent)
		}
		sort.Strings(parents)
		classes = append(classes, class{name: c.Name, abstract: c.Abstract, parents: parents})
		for _, f := range c.Features {
			p, err := newProperty(c.Name, f, kinds, features)
			if err != nil {
				return nil, nil, fmt.Errorf("%s::%s: %w", c.Name, f.Name, err)
			}
			properties = append(properties, p)
		}
	}
	sort.Slice(properties, func(i, j int) bool { return properties[i].iri < properties[j].iri })
	sort.Slice(classes, func(i, j int) bool { return classes[i].name < classes[j].name })
	return properties, classes, nil
}

func newProperty(defining string, f eFeature, kinds map[string]string, features map[string]bool) (property, error) {
	if f.Name == "" || strings.Contains(f.Name, "_") {
		return property{}, fmt.Errorf("feature name %q cannot form a <Metaclass>_<name> IRI", f.Name)
	}
	many, err := isMany(f.UpperBound)
	if err != nil {
		return property{}, err
	}
	p := property{
		name:          f.Name,
		definingClass: defining,
		iri:           sysmlNS + defining + "_" + f.Name,
		many:          many,
		derived:       f.Derived,
	}
	p.ordered = p.many && f.Ordered != "false"
	local, isLocal := strings.CutPrefix(f.EType, "#//")
	switch {
	case f.Type == "ecore:EReference" && isLocal && kinds[local] == "ecore:EClass":
		p.kind, p.rangeIRI = "ObjectProperty", sysmlNS+local
	case f.Type == "ecore:EAttribute" && isLocal && kinds[local] == "ecore:EEnum":
		p.kind, p.rangeIRI = "DatatypeProperty", sysmlNS+local
	case f.Type == "ecore:EAttribute" && !isLocal:
		_, primitive, _ := strings.Cut(f.EType, "#//")
		if p.rangeIRI = datatypeRanges[primitive]; p.rangeIRI == "" {
			return property{}, fmt.Errorf("eType %q is no primitive the table maps", f.EType)
		}
		p.kind = "DatatypeProperty"
	default:
		return property{}, fmt.Errorf("a %s typed %q, which the table cannot range over", f.Type, f.EType)
	}
	if f.Opposite != "" {
		var opposite []string
		if opposite, err = featureRefs(f.Opposite, features); err != nil {
			return property{}, fmt.Errorf("eOpposite: %w", err)
		}
		if len(opposite) != 1 {
			return property{}, fmt.Errorf("eOpposite %q names %d features", f.Opposite, len(opposite))
		}
		p.opposite = opposite[0]
	}
	for _, a := range f.Annotations {
		switch a.Source {
		case "redefines":
			p.redefines, err = featureRefs(a.References, features)
		case "subsets":
			p.subsets, err = featureRefs(a.References, features)
		}
		if err != nil {
			return property{}, fmt.Errorf("%s: %w", a.Source, err)
		}
	}
	return p, nil
}

// featureRefs turns "#//Class/feature ..." references into "Class::feature" names, each a declared feature.
// isMany reports whether an ecore upperBound admits more than one value: any bound
// above 1, or -1 (unbounded). An absent upperBound is ecore's default, 1.
func isMany(upperBound string) (bool, error) {
	if upperBound == "" {
		return false, nil
	}
	n, err := strconv.Atoi(upperBound)
	if err != nil || n == 0 || n < -1 {
		return false, fmt.Errorf("upperBound %q is neither a positive integer nor -1 (unbounded)", upperBound)
	}
	return n != 1, nil
}

func featureRefs(refs string, features map[string]bool) ([]string, error) {
	var out []string
	for _, ref := range strings.Fields(refs) {
		path, ok := strings.CutPrefix(ref, "#//")
		owner, name, qualified := strings.Cut(path, "/")
		if !ok || !qualified || !features[owner+"::"+name] {
			return nil, fmt.Errorf("%s is no eStructuralFeature of the package", ref)
		}
		out = append(out, owner+"::"+name)
	}
	return out, nil
}

func propertyLiterals(properties []property) string {
	var b strings.Builder
	for _, p := range properties {
		fmt.Fprintf(&b, "\t{Name: %q, DefiningClass: %q, IRI: %q, Kind: %s, Range: %q",
			p.name, p.definingClass, p.iri, p.kind, p.rangeIRI)
		for _, flag := range []struct {
			name string
			set  bool
		}{{"Many", p.many}, {"Ordered", p.ordered}, {"Derived", p.derived}} {
			if flag.set {
				fmt.Fprintf(&b, ", %s: true", flag.name)
			}
		}
		if len(p.redefines) > 0 {
			fmt.Fprintf(&b, ", Redefines: %s", stringSlice(p.redefines))
		}
		if len(p.subsets) > 0 {
			fmt.Fprintf(&b, ", Subsets: %s", stringSlice(p.subsets))
		}
		if p.opposite != "" {
			fmt.Fprintf(&b, ", Opposite: %q", p.opposite)
		}
		b.WriteString("},\n")
	}
	return b.String()
}

func classLiterals(classes []class) string {
	var b strings.Builder
	for _, c := range classes {
		fmt.Fprintf(&b, "\t{Name: %q", c.name)
		if c.abstract {
			b.WriteString(", Abstract: true")
		}
		if len(c.parents) > 0 {
			fmt.Fprintf(&b, ", Parents: %s", stringSlice(c.parents))
		}
		b.WriteString("},\n")
	}
	return b.String()
}

func enumerationLiterals(enums []enumeration) string {
	var b strings.Builder
	for _, enum := range enums {
		fmt.Fprintf(&b, "\t{Name: %q, Literals: %s},\n", enum.name, stringSlice(enum.literals))
	}
	return b.String()
}

func stringSlice(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}
