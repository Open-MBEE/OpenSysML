// Command ontology writes internal/core/rdf/ontology/table.go from a local
// checkout of https://github.com/Open-MBEE/sysmlv2-rdf-ontology, which is not
// vendored here. The checkout's version and commit SHA go into the header,
// making the table reproducible.
//
//	go run -C tools ./gen/ontology -ontology /path/to/sysmlv2-rdf-ontology
package main

import (
	"encoding/xml"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/Open-MBEE/OpenSysML/tools/oracle/repo"
)

// tablePath is the generated table, relative to the repository root.
const tablePath = "internal/core/rdf/ontology/table.go"

const (
	sysmlNS  = "https://www.omg.org/spec/SysML#"
	owlPath  = "sysml2/owl/www.omg.org/spec/SysML.owl"
	readme   = "sysml2/README.md"
	rdfNS    = "http://www.w3.org/1999/02/22-rdf-syntax-ns#"
	rdfsNS   = "http://www.w3.org/2000/01/rdf-schema#"
	owlNS    = "http://www.w3.org/2002/07/owl#"
	template = `// Code generated by tools/gen/ontology. DO NOT EDIT.
//
// Source:   Open-MBEE/sysmlv2-rdf-ontology, %s
// Ontology: SysML v2 metamodel version %s (generated from SysML.ecore)
// Commit:   %s
//
// Regenerate with (see README.md):
//
//	go run -C tools ./gen/ontology -ontology <path to sysmlv2-rdf-ontology checkout>

package ontology

// Version is the OMG SysML v2 metamodel version the table was generated from.
const Version = %q

// SourceCommit is the sysmlv2-rdf-ontology commit the table was generated from.
const SourceCommit = %q

// properties holds every owl:ObjectProperty and owl:DatatypeProperty the
// ontology declares, ordered by IRI.
var properties = []Property{
%s}

// classes holds every owl:Class the ontology declares with its named
// rdfs:subClassOf parents, ordered by name.
var classes = []Class{
%s}
`
)

func main() {
	root := flag.String("ontology", "", "path to a local Open-MBEE/sysmlv2-rdf-ontology checkout")
	out := flag.String("out", "", "generated file to write (default "+tablePath+" under the repository root)")
	flag.Parse()
	if *root == "" {
		fail(fmt.Errorf("-ontology is required: pass a local sysmlv2-rdf-ontology checkout"))
	}
	if *out == "" {
		repoRoot, err := repo.Root()
		if err != nil {
			fail(err)
		}
		*out = filepath.Join(repoRoot, filepath.FromSlash(tablePath))
	}
	if err := run(*root, *out); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "ontology:", err)
	os.Exit(1)
}

func run(root, out string) error {
	version, err := ontologyVersion(filepath.Join(root, readme))
	if err != nil {
		return err
	}
	commit, err := commitSHA(root)
	if err != nil {
		return err
	}
	decls, err := parseOntology(filepath.Join(root, owlPath))
	if err != nil {
		return err
	}
	properties, classes, err := tables(decls)
	if err != nil {
		return err
	}
	source := fmt.Sprintf(template, owlPath, version, commit, version, commit,
		propertyLiterals(properties), classLiterals(classes))
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(out, formatted, 0o600); err != nil {
		return err
	}
	fmt.Printf("wrote %s: %d properties, %d classes (version %s, commit %s)\n",
		out, len(properties), len(classes), version, commit[:12])
	return nil
}

var (
	versionBadge     = regexp.MustCompile(`Version-(\d+)-`)
	commitSHAPattern = regexp.MustCompile(`^([0-9a-f]{40}|[0-9a-f]{64})$`)
)

// ontologyVersion reads the metamodel version out of the checkout's own README
// badge, so the recorded version cannot drift from the file it describes.
func ontologyVersion(path string) (string, error) {
	// #nosec G304 -- the checkout to read is named on the command line.
	data, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("read ontology version: %w", err)
	}
	match := versionBadge.FindSubmatch(data)
	if match == nil {
		return "", fmt.Errorf("no Version-<n> badge in %s", path)
	}
	return string(match[1]), nil
}

func commitSHA(root string) (string, error) {
	gitDir, refsDir, err := gitMetadataDirs(root)
	if err != nil {
		return "", err
	}
	headPath := filepath.Join(gitDir, "HEAD")
	// #nosec G304 -- git metadata path derives from the requested checkout.
	head, err := os.ReadFile(headPath)
	if err != nil {
		return "", gitMetadataErrorf(headPath, "read HEAD: %w", err)
	}
	headValue := strings.TrimSpace(string(head))
	if strings.HasPrefix(headValue, "ref:") {
		ref := strings.TrimSpace(strings.TrimPrefix(headValue, "ref:"))
		if !validGitRef(ref) {
			return "", gitMetadataErrorf(headPath, "invalid symbolic ref %q", ref)
		}
		return commitSHAForRef(refsDir, ref)
	}
	return validateCommitSHA(headValue, headPath)
}

type gitMetadataError struct {
	path string
	err  error
}

func (e *gitMetadataError) Error() string {
	return fmt.Sprintf("git metadata %s: %v", e.path, e.err)
}

func (e *gitMetadataError) Unwrap() error {
	return e.err
}

func gitMetadataErrorf(path, format string, args ...any) error {
	return &gitMetadataError{path: path, err: fmt.Errorf(format, args...)}
}

func gitMetadataDirs(root string) (string, string, error) {
	dotGit := filepath.Join(root, ".git")
	info, err := os.Stat(dotGit)
	if err != nil {
		return "", "", gitMetadataErrorf(dotGit, "read .git: %w", err)
	}
	gitDir := dotGit
	if !info.IsDir() {
		// #nosec G304 -- .git is derived from the requested checkout.
		data, err := os.ReadFile(dotGit)
		if err != nil {
			return "", "", gitMetadataErrorf(dotGit, "read gitdir: %w", err)
		}
		line := strings.TrimSpace(string(data))
		const prefix = "gitdir:"
		if !strings.HasPrefix(line, prefix) {
			return "", "", gitMetadataErrorf(dotGit, "invalid gitdir file")
		}
		target := strings.TrimSpace(strings.TrimPrefix(line, prefix))
		if target == "" {
			return "", "", gitMetadataErrorf(dotGit, "empty gitdir path")
		}
		if !filepath.IsAbs(target) {
			target = filepath.Join(root, target)
		}
		gitDir = filepath.Clean(target)
		info, err = os.Stat(gitDir)
		if err != nil {
			return "", "", gitMetadataErrorf(dotGit, "read gitdir %s: %w", gitDir, err)
		}
		if !info.IsDir() {
			return "", "", gitMetadataErrorf(dotGit, "gitdir %s is not a directory", gitDir)
		}
	}

	refsDir := gitDir
	commondirPath := filepath.Join(gitDir, "commondir")
	// #nosec G304 -- commondir is inside the requested Git metadata directory.
	data, err := os.ReadFile(commondirPath)
	if err == nil {
		commonDir := strings.TrimSpace(string(data))
		if commonDir == "" {
			return "", "", gitMetadataErrorf(commondirPath, "empty common directory path")
		}
		if !filepath.IsAbs(commonDir) {
			commonDir = filepath.Join(gitDir, commonDir)
		}
		refsDir = filepath.Clean(commonDir)
		info, err := os.Stat(refsDir)
		if err != nil {
			return "", "", gitMetadataErrorf(commondirPath, "read common directory %s: %w", refsDir, err)
		}
		if !info.IsDir() {
			return "", "", gitMetadataErrorf(commondirPath, "common directory %s is not a directory", refsDir)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", "", gitMetadataErrorf(commondirPath, "read common directory: %w", err)
	}
	return gitDir, refsDir, nil
}

func validGitRef(ref string) bool {
	if !strings.HasPrefix(ref, "refs/") || strings.ContainsAny(ref, " \t\r\n") {
		return false
	}
	for _, part := range strings.Split(ref, "/") {
		if part == "" || part == "." || part == ".." {
			return false
		}
	}
	return true
}

func commitSHAForRef(refsDir, ref string) (string, error) {
	loosePath := filepath.Join(refsDir, filepath.FromSlash(ref))
	// #nosec G304 -- ref is validated before it is joined to the Git directory.
	data, err := os.ReadFile(loosePath)
	if err == nil {
		return validateCommitSHA(strings.TrimSpace(string(data)), loosePath)
	}
	if !errors.Is(err, os.ErrNotExist) {
		return "", gitMetadataErrorf(loosePath, "read ref %s: %w", ref, err)
	}

	packedPath := filepath.Join(refsDir, "packed-refs")
	// #nosec G304 -- packed-refs is inside the requested Git metadata directory.
	data, err = os.ReadFile(packedPath)
	if err != nil {
		return "", gitMetadataErrorf(packedPath, "read ref %s: %w", ref, err)
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, "^") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 2 || fields[1] != ref {
			continue
		}
		return validateCommitSHA(fields[0], packedPath)
	}
	return "", gitMetadataErrorf(packedPath, "ref %s not found", ref)
}

func validateCommitSHA(sha, path string) (string, error) {
	if !commitSHAPattern.MatchString(sha) {
		return "", gitMetadataErrorf(path, "invalid commit SHA %q", sha)
	}
	return sha, nil
}

// declaration is one top-level RDF/XML declaration in the ontology: an
// owl:Class, owl:ObjectProperty or owl:DatatypeProperty.
type declaration struct {
	kind     string
	iri      string
	label    string
	domain   string
	rangeIRI string
	parents  []string
}

// parseOntology reads the declarations out of the RDF/XML. Only top-level elements
// of rdf:RDF are read; the anonymous owl:Restriction axioms nested inside them
// state cardinality rather than hierarchy.
func parseOntology(path string) ([]declaration, error) {
	// #nosec G304 -- the checkout to read is named on the command line.
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	decoder := xml.NewDecoder(file)
	var (
		decls []declaration
		depth int
	)
	for {
		token, err := decoder.Token()
		if err != nil {
			if errors.Is(err, io.EOF) {
				break
			}
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		start, ok := token.(xml.StartElement)
		if !ok {
			if _, isEnd := token.(xml.EndElement); isEnd {
				depth--
			}
			continue
		}
		depth++
		if depth != 2 {
			continue
		}
		kind := start.Name.Space + start.Name.Local
		switch kind {
		case owlNS + "Class", owlNS + "ObjectProperty", owlNS + "DatatypeProperty":
		default:
			continue
		}
		decl, err := readDeclaration(decoder, start)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		depth--
		decl.kind = start.Name.Local
		decls = append(decls, decl)
	}
	if len(decls) == 0 {
		return nil, fmt.Errorf("%s: no declarations found", path)
	}
	return decls, nil
}

// readDeclaration consumes one declaration element, reading the direct children
// that carry the table's data and skipping the rest.
func readDeclaration(decoder *xml.Decoder, start xml.StartElement) (declaration, error) {
	decl := declaration{iri: attr(start, rdfNS, "about")}
	if decl.iri == "" {
		return decl, fmt.Errorf("%s declaration without rdf:about", start.Name.Local)
	}
	for {
		token, err := decoder.Token()
		if err != nil {
			return decl, err
		}
		switch t := token.(type) {
		case xml.EndElement:
			if t.Name == start.Name {
				return decl, nil
			}
		case xml.StartElement:
			name := t.Name.Space + t.Name.Local
			resource := attr(t, rdfNS, "resource")
			switch {
			case name == rdfsNS+"label":
				text, err := decoder.Token()
				if err != nil {
					return decl, err
				}
				if chars, ok := text.(xml.CharData); ok {
					decl.label = strings.TrimSpace(string(chars))
				}
			case name == rdfsNS+"domain" && resource != "":
				decl.domain = resource
			case name == rdfsNS+"range" && resource != "":
				decl.rangeIRI = resource
			case name == rdfsNS+"subClassOf" && resource != "":
				decl.parents = append(decl.parents, resource)
			default:
				if resource == "" {
					if err := decoder.Skip(); err != nil {
						return decl, err
					}
				}
			}
		}
	}
}

func attr(element xml.StartElement, space, local string) string {
	for _, a := range element.Attr {
		if a.Name.Local == local && (a.Name.Space == space || a.Name.Space == "") {
			return a.Value
		}
	}
	return ""
}

// property and class mirror the generated table's types, which cannot be imported:
// the package they live in does not compile until this has run.
type property struct {
	name, definingClass, iri, kind, rangeIRI string
}

type class struct {
	name    string
	parents []string
}

func tables(decls []declaration) ([]property, []class, error) {
	var (
		properties []property
		classes    []class
	)
	for _, decl := range decls {
		if !strings.HasPrefix(decl.iri, sysmlNS) {
			return nil, nil, fmt.Errorf("declaration outside the SysML namespace: %s", decl.iri)
		}
		local := strings.TrimPrefix(decl.iri, sysmlNS)
		if decl.kind == "Class" {
			var parents []string
			for _, parent := range decl.parents {
				if strings.HasPrefix(parent, sysmlNS) {
					parents = append(parents, strings.TrimPrefix(parent, sysmlNS))
				}
			}
			sort.Strings(parents)
			classes = append(classes, class{name: local, parents: parents})
			continue
		}
		defining, name, ok := strings.Cut(local, "_")
		if !ok {
			return nil, nil, fmt.Errorf("property IRI is not <Metaclass>_<name>: %s", decl.iri)
		}
		// The label is the unqualified name; disagreement with the IRI would
		// mean the two conventions cannot be mapped onto each other by name.
		if decl.label != "" && decl.label != name {
			return nil, nil, fmt.Errorf("%s: rdfs:label %q does not match the IRI's property name %q",
				decl.iri, decl.label, name)
		}
		if decl.domain == "" {
			return nil, nil, fmt.Errorf("%s: no rdfs:domain", decl.iri)
		}
		if domain := strings.TrimPrefix(decl.domain, sysmlNS); domain != defining {
			return nil, nil, fmt.Errorf("%s: rdfs:domain %s is not the qualifying metaclass %s",
				decl.iri, domain, defining)
		}
		kind := "ObjectProperty"
		if decl.kind == "DatatypeProperty" {
			kind = "DatatypeProperty"
		}
		properties = append(properties, property{
			name:          name,
			definingClass: defining,
			iri:           decl.iri,
			kind:          kind,
			rangeIRI:      decl.rangeIRI,
		})
	}
	sort.Slice(properties, func(i, j int) bool { return properties[i].iri < properties[j].iri })
	sort.Slice(classes, func(i, j int) bool { return classes[i].name < classes[j].name })
	return properties, classes, nil
}

func propertyLiterals(properties []property) string {
	var b strings.Builder
	for _, p := range properties {
		fmt.Fprintf(&b, "\t{Name: %q, DefiningClass: %q, IRI: %q, Kind: %s, Range: %q},\n",
			p.name, p.definingClass, p.iri, p.kind, p.rangeIRI)
	}
	return b.String()
}

func classLiterals(classes []class) string {
	var b strings.Builder
	for _, c := range classes {
		if len(c.parents) == 0 {
			fmt.Fprintf(&b, "\t{Name: %q},\n", c.name)
			continue
		}
		quoted := make([]string, len(c.parents))
		for i, parent := range c.parents {
			quoted[i] = fmt.Sprintf("%q", parent)
		}
		fmt.Fprintf(&b, "\t{Name: %q, Parents: []string{%s}},\n", c.name, strings.Join(quoted, ", "))
	}
	return b.String()
}
