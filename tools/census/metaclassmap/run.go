package metaclassmap

import (
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"github.com/Open-MBEE/OpenSysML/tools/census/grammar"
	"github.com/Open-MBEE/OpenSysML/tools/oracle/repo"
)

// Main runs the grammar-metaclass-map command and returns its exit status.
func Main(args []string, stderr io.Writer) int {
	flags := flag.NewFlagSet("grammar-metaclass-map", flag.ContinueOnError)
	flags.SetOutput(stderr)
	repoDir := flags.String("repo", "", "repository root (default: the module root containing this command)")
	grammars := flags.String("grammars", "", "directory holding the .xtext grammars (default: <repo>/build/pilot-grammars)")
	out := flags.String("out", "", "output directory for the reports (default: <repo>/build/grammar-metaclass-map)")
	baseline := flags.String("baseline", "", "also write the compact baseline JSON to this file")
	if err := flags.Parse(args); err != nil {
		if err == flag.ErrHelp {
			return 0
		}
		return 2
	}
	if err := run(*repoDir, *grammars, *out, *baseline, stderr); err != nil {
		fmt.Fprintf(stderr, "grammar-metaclass-map: %v\n", err)
		return 1
	}
	return 0
}

func run(repoDir, grammarDir, outDir, baseline string, log io.Writer) error {
	if log == nil {
		log = io.Discard
	}
	root, err := repo.Choose(repoDir)
	if err != nil {
		return err
	}
	grammarDir = repo.Resolve(root, grammarDir)
	outDir, baseline = repo.Resolve(root, outDir), repo.Resolve(root, baseline)
	if grammarDir == "" {
		grammarDir = filepath.Join(root, "build", "pilot-grammars")
	}
	if outDir == "" {
		outDir = filepath.Join(root, "build", "grammar-metaclass-map")
	}
	coverage, grammars, err := grammar.Measure(root, grammarDir, log)
	if err != nil {
		return err
	}
	shapes := grammar.Shapes(grammars)
	files := map[string][]byte{}
	for _, doc := range evidenceDocuments(coverage) {
		// #nosec G304 -- coverage citations are repository-relative paths generated by the census.
		content, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(doc)))
		if err != nil {
			return fmt.Errorf("read evidence %s: %w", doc, err)
		}
		files[doc] = content
	}
	report, err := Analyze(coverage, shapes, files)
	if err != nil {
		return err
	}
	if err := writeReports(outDir, report, log); err != nil {
		return err
	}
	if baseline != "" {
		if err := writeBaseline(baseline, report, log); err != nil {
			return err
		}
	}
	return nil
}
