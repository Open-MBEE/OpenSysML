// Generate statically typed TypeScript classes from a SysML model.
//
// Usage: `opensysml-generate model.sysml -o model_types.ts`
//
// The generated module contains one class per SysML definition, deriving from
// TypedObject, with one getter per feature. Emission is deterministic —
// symbols are ordered by fully-qualified name and nothing environment-
// dependent is written — so the output can be committed as a golden file, and
// --check can gate that it is current.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import {
  CAPABILITY_TYPE_FACTS,
  MissingCapabilityError,
  requireCapability,
} from "../core/capabilities.js";
import type { Connection } from "../core/connection.js";
import type { Model, SpecializationFacts, TypeFacts } from "../core/model.js";
import { PACKAGE_NAME } from "../core/package.js";
import { connect } from "./index.js";

export const GENERATED_HEADER = "// Generated by opensysml-generate. Do not edit.";

// Decoder for a feature whose SysML type has no sound TypeScript type.
const OBJECT_DECODER = "_t.asObject";

// Emission schema, bumped when this generator's output changes for an
// unchanged model. Not the opensysml release version, which would churn
// every module.
export const GENERATOR_VERSION = "5";

// The stamp hashes the model source client-side. A path, a timestamp or the
// service version would churn without the module's content changing.
export const MODEL_HASH_ALGORITHM = "sha256";

// What a module rendered without the model source says, so it cannot be
// mistaken for one stamped with a real hash.
export const UNSTAMPED = "unstamped";

// Definition kinds get a class; these usage kinds become properties on the
// enclosing class. Behavioral and connector usages (action, state, calc,
// constraint, requirement, connection, flow, interface, allocation, case) are
// not instance feature values and are skipped.
const FEATURE_KINDS = new Set([
  "attributeusage",
  "referenceusage",
  "partusage",
  "itemusage",
  "occurrenceusage",
  "individualusage",
  "portusage",
  "enumusage",
]);

// The generalization edges that make one element a kind of another. A typing
// edge is the element's type, not a supertype of it, so it is not one of these.
const GENERALIZATION_KINDS = new Set(["specializes", "subsets", "redefines"]);

// How far a generalization chain is followed for a fact a declaration leaves out.
const MAX_GENERALIZATION_DEPTH = 16;

const PRIMITIVE_TYPES = new Map<string, { annotation: string; decoder: string }>([
  ["Boolean", { annotation: "boolean", decoder: "_t.asBoolean" }],
  ["String", { annotation: "string", decoder: "_t.asString" }],
  ["Natural", { annotation: "bigint", decoder: "_t.asInt" }],
  ["Integer", { annotation: "bigint", decoder: "_t.asInt" }],
  ["Rational", { annotation: "_t.RationalValue", decoder: "_t.asRational" }],
  ["Real", { annotation: "number", decoder: "_t.asReal" }],
  ["Complex", { annotation: "_t.ComplexValue", decoder: "_t.asComplex" }],
]);

// Library scalars with no sound TypeScript counterpart, mapped to object:
// Number is the supertype of every numeric scalar, so a Number slot may hold
// any of them.
const UNMAPPED_PRIMITIVES = new Set(["Number"]);

// Members TypedObject itself provides; a getter of the same name would shadow
// the machinery the accessors use, so such a feature is renamed.
const RESERVED_MEMBERS = new Set([
  "instance",
  "fromInstance",
  "unchecked",
  "sysmlId",
  "resolver",
]);

// Words TypeScript and JavaScript reserve; a getter or class may not be one.
const RESERVED_WORDS = new Set([
  "break", "case", "catch", "class", "const", "continue", "debugger",
  "default", "delete", "do", "else", "enum", "export", "extends", "false",
  "finally", "for", "function", "if", "implements", "import", "in",
  "instanceof", "interface", "let", "new", "null", "package", "private",
  "protected", "public", "return", "static", "super", "switch", "this",
  "throw", "true", "try", "typeof", "undefined", "var", "void", "while",
  "with", "yield",
]);

/** Whether a symbol kind declares a type, e.g. `partDef` or `metaclass`. */
export function isDefinitionKind(kind: string): boolean {
  const lowered = kind.toLowerCase();
  return lowered.endsWith("def") || lowered === "metaclass";
}

/** Whether a symbol kind is a usage exposed as an instance feature. */
export function isFeatureKind(kind: string): boolean {
  return FEATURE_KINDS.has(kind.toLowerCase());
}

/** One SysML feature to emit as a getter. */
export interface Feature {
  readonly id: string;
  readonly name: string;
  readonly kind: string;
  readonly type?: TypeFacts | undefined;
  readonly multiplicity?: { lower: string; upper: string } | undefined;
}

interface FeatureFacts {
  readonly id: string;
  readonly name: string;
  readonly kind: string;
  readonly type?: TypeFacts | undefined;
  readonly multiplicity?: { lower: string; upper: string } | undefined;
  readonly specializations: readonly SpecializationFacts[];
}

/** One SysML definition to emit as a class. */
export class Definition {
  readonly id: string;
  readonly name: string;
  readonly kind: string;
  readonly specializations: readonly SpecializationFacts[];
  readonly features: readonly Feature[];

  constructor(init: {
    id: string;
    name: string;
    kind: string;
    specializations?: readonly SpecializationFacts[] | undefined;
    features?: readonly Feature[] | undefined;
  }) {
    this.id = init.id;
    this.name = init.name;
    this.kind = init.kind;
    this.specializations = init.specializations ?? [];
    this.features = init.features ?? [];
  }

  /** FQNs of what this definition specializes, subsets or redefines, in
   * declaration order, without repetition. */
  get baseIds(): readonly string[] {
    const ordered: string[] = [];
    for (const spec of this.specializations) {
      if (GENERALIZATION_KINDS.has(spec.kind) && spec.targetId !== "" && !ordered.includes(spec.targetId)) {
        ordered.push(spec.targetId);
      }
    }
    return ordered;
  }
}

/** A rendered TypeScript annotation plus the decoder and note behind it. */
export interface TypeScriptType {
  readonly annotation: string;
  readonly decoder: string;
  readonly comment: string;
}

/** A symbol in a symbol tree; {@link ModelSymbol} satisfies this structurally. */
export interface SymbolTree {
  readonly id: string;
  readonly name: string;
  readonly kind: string;
  readonly type?: TypeFacts | undefined;
  readonly multiplicity?: { lower: string; upper: string } | undefined;
  readonly specializations?: readonly SpecializationFacts[] | undefined;
  children(): Promise<readonly SymbolTree[]>;
}

/** Collect the definitions in one or more symbol trees, sorted by FQN, each
 * feature taking the type and multiplicity it inherits. */
export async function collectDefinitions(...roots: readonly SymbolTree[]): Promise<Definition[]> {
  const definitions: Definition[] = [];
  const factsById = new Map<string, FeatureFacts>();
  await Promise.all(roots.map((root) => collect(root, definitions, factsById)));
  const resolved = definitions.map((definition) => withInheritedFacts(definition, factsById));
  resolved.sort((left, right) => left.id.localeCompare(right.id));
  return resolved;
}

async function collect(
  symbol: SymbolTree,
  out: Definition[],
  factsById: Map<string, FeatureFacts>,
): Promise<void> {
  const children = await symbol.children();
  factsById.set(symbol.id, {
    id: symbol.id,
    name: symbol.name,
    kind: symbol.kind,
    type: symbol.type,
    multiplicity: symbol.multiplicity,
    specializations: symbol.specializations ?? [],
  });
  if (isDefinitionKind(symbol.kind)) {
    const featureChildren = children
      .filter((child) => isFeatureKind(child.kind))
      .sort((left, right) => left.id.localeCompare(right.id));
    out.push(
      new Definition({
        id: symbol.id,
        name: symbol.name,
        kind: symbol.kind,
        specializations: symbol.specializations,
        features: featureChildren.map((child) => ({
          id: child.id,
          name: child.name,
          kind: child.kind,
          type: child.type,
          multiplicity: child.multiplicity,
        })),
      }),
    );
  }
  await Promise.all(children.map((child) => collect(child, out, factsById)));
}

function withInheritedFacts(
  definition: Definition,
  factsById: Map<string, FeatureFacts>,
): Definition {
  return new Definition({
    id: definition.id,
    name: definition.name,
    kind: definition.kind,
    specializations: definition.specializations,
    features: definition.features.map((feature) =>
      resolvedFeature(feature, factsById),
    ),
  });
}

function resolvedFeature(feature: Feature, factsById: Map<string, FeatureFacts>): Feature {
  const owner = factsById.get(feature.id);
  const specializations = owner?.specializations ?? [];

  let typeFacts = feature.type;
  if (!namesAType(typeFacts)) {
    const inherited = inheritedFact(
      { specializations },
      factsById,
      (other) => (namesAType(other.type) ? other.type : undefined),
    );
    if (inherited !== undefined) {
      typeFacts = mergedType(typeFacts, inherited);
    }
  }

  const multiplicity = feature.multiplicity ?? inheritedFact(
    { specializations },
    factsById,
    (other) => other.multiplicity,
  );

  if (typeFacts === feature.type && multiplicity === feature.multiplicity) {
    return feature;
  }
  return { ...feature, type: typeFacts, multiplicity };
}

function inheritedFact<F>(
  facts: { specializations: readonly SpecializationFacts[] },
  factsById: Map<string, FeatureFacts>,
  pick: (other: FeatureFacts) => F | undefined,
  depth = 0,
): F | undefined {
  if (depth >= MAX_GENERALIZATION_DEPTH) {
    return undefined;
  }
  for (const spec of facts.specializations) {
    if (!GENERALIZATION_KINDS.has(spec.kind) || spec.targetId === "") {
      continue;
    }
    const target = factsById.get(spec.targetId);
    if (target === undefined) {
      continue;
    }
    const found = pick(target);
    if (found !== undefined) {
      return found;
    }
    const deeper = inheritedFact(target, factsById, pick, depth + 1);
    if (deeper !== undefined) {
      return deeper;
    }
  }
  return undefined;
}

function namesAType(typeFacts: TypeFacts | undefined): boolean {
  return typeFacts !== undefined && (typeFacts.resolvedId !== "" || typeFacts.declared !== "");
}

function mergedType(own: TypeFacts | undefined, inherited: TypeFacts): TypeFacts {
  if (own === undefined) {
    return inherited;
  }
  return {
    declared: inherited.declared,
    resolvedId: inherited.resolvedId,
    resolvedKind: inherited.resolvedKind,
    primitive: own.primitive !== "" ? own.primitive : inherited.primitive,
    primitiveSource: own.primitiveSource !== "" ? own.primitiveSource : inherited.primitiveSource,
    quantity: own.quantity || inherited.quantity,
    unit: own.unit !== "" ? own.unit : inherited.unit,
  };
}

/** Map definition FQN → TypeScript class name.
 *
 * A simple name declared by more than one definition is qualified with its
 * owning path so that every generated class name is unique and stable. */
export function classNames(definitions: readonly Definition[]): Map<string, string> {
  const byName = new Map<string, Definition[]>();
  for (const definition of definitions) {
    const simple = identifier(definition.name);
    const group = byName.get(simple) ?? [];
    group.push(definition);
    byName.set(simple, group);
  }
  const names = new Map<string, string>();
  for (const [simple, group] of byName) {
    if (group.length === 1) {
      names.set(group[0].id, simple);
      continue;
    }
    for (const definition of group) {
      names.set(
        definition.id,
        definition.id.split("::").map(identifier).join("_"),
      );
    }
  }
  return names;
}

function identifier(name: string): string {
  let cleaned = Array.from(name)
    .map((char) => (/[\p{L}\p{N}_]/u.test(char) ? char : "_"))
    .join("");
  if (cleaned === "" || /^\d/.test(cleaned)) {
    cleaned = `_${cleaned}`;
  }
  if (RESERVED_WORDS.has(cleaned)) {
    cleaned += "_";
  }
  return cleaned;
}

function literal(text: string): string {
  return JSON.stringify(text);
}

/** TypeScript name of the getter for a feature; the SysML feature name is unchanged. */
export function propertyName(name: string): string {
  let ident = identifier(name);
  if (RESERVED_MEMBERS.has(ident)) {
    ident += "_";
  }
  return ident;
}

/** Map the type of a single value to a TypeScript annotation and decoder. */
export function elementType(
  typeFacts: TypeFacts | undefined,
  names: Map<string, string>,
): TypeScriptType {
  if (typeFacts === undefined) {
    return { annotation: "_t.SysMLValue", decoder: OBJECT_DECODER, comment: "untyped feature" };
  }

  // A value written with a unit is a magnitude and that unit, whatever library
  // scalar the magnitude reduces to, so it is typed before the primitive below.
  if (typeFacts.quantity && typeFacts.unit !== "") {
    return {
      annotation: "_t.Quantity",
      decoder: "_t.asQuantity",
      comment: `quantity in [${typeFacts.unit}]`,
    };
  }
  if (typeFacts.quantity) {
    // A quantity value type constrains the type, not what is written for it.
    return {
      annotation: "_t.SysMLValue",
      decoder: OBJECT_DECODER,
      comment: "quantity value type, no unit written",
    };
  }

  // A definition reducing to a library scalar holds that scalar, not an
  // instance, even when it has a generated class of its own.
  const primitive = PRIMITIVE_TYPES.get(typeFacts.primitive);
  if (primitive !== undefined) {
    return { annotation: primitive.annotation, decoder: primitive.decoder, comment: "" };
  }

  // An enumeration-typed feature holds one of the enumeration's literals, a
  // value of its own rather than an instance of the generated class.
  if (typeFacts.resolvedKind === "enumDef") {
    return { annotation: "_t.EnumValue", decoder: "_t.asEnum", comment: "" };
  }

  const generated = names.get(typeFacts.resolvedId);
  if (typeFacts.resolvedId !== "" && generated !== undefined) {
    return { annotation: generated, decoder: `_t.asTyped(${generated})`, comment: "" };
  }

  if (UNMAPPED_PRIMITIVES.has(typeFacts.primitive)) {
    return {
      annotation: "_t.SysMLValue",
      decoder: OBJECT_DECODER,
      comment: `SysML ${typeFacts.primitive} has no TypeScript counterpart`,
    };
  }

  if (typeFacts.resolvedId !== "") {
    return {
      annotation: "_t.SysMLValue",
      decoder: OBJECT_DECODER,
      comment: `SysML type ${typeFacts.resolvedId} has no generated class`,
    };
  }

  if (typeFacts.declared !== "") {
    return {
      annotation: "_t.SysMLValue",
      decoder: OBJECT_DECODER,
      comment: `unresolved SysML type ${typeFacts.declared}`,
    };
  }

  return { annotation: "_t.SysMLValue", decoder: OBJECT_DECODER, comment: "untyped feature" };
}

interface MultiplicityRange {
  lower: string;
  upper: string;
}

const EMPTY_MULTIPLICITY: MultiplicityRange = { lower: "", upper: "" };

function isCollection(multiplicity: MultiplicityRange): boolean | undefined {
  if (multiplicity.upper === "") {
    return undefined;
  }
  if (multiplicity.upper === "*") {
    return true;
  }
  const upper = Number.parseInt(multiplicity.upper, 10);
  return Number.isNaN(upper) ? undefined : upper > 1;
}

function isOptional(multiplicity: MultiplicityRange): boolean | undefined {
  if (multiplicity.lower === "") {
    return undefined;
  }
  const lower = Number.parseInt(multiplicity.lower, 10);
  return Number.isNaN(lower) ? undefined : lower === 0;
}

/** Map a feature to its TypeScript annotation, decoder and accessor, honoring multiplicity. */
export function featureType(feature: Feature, names: Map<string, string>): TypeScriptType {
  const element = elementType(feature.type, names);
  const multiplicity = feature.multiplicity ?? EMPTY_MULTIPLICITY;
  if (isCollection(multiplicity)) {
    return { ...element, annotation: `readonly ${element.annotation}[]` };
  }
  if (isOptional(multiplicity)) {
    return { ...element, annotation: `${element.annotation} | undefined` };
  }
  return element;
}

function accessor(feature: Feature): string {
  const multiplicity = feature.multiplicity ?? EMPTY_MULTIPLICITY;
  if (isCollection(multiplicity)) {
    return "_t.listFeatureValue";
  }
  if (isOptional(multiplicity)) {
    return "_t.optionalFeatureValue";
  }
  return "_t.featureValue";
}

/** Hash of the model source a generated module was produced from.
 *
 * Newlines are normalized so the same model checked out with CRLF endings
 * stamps identically; nothing else about the text is interpreted. */
export function modelStamp(sourceText: string): string {
  const normalized = sourceText.replaceAll("\r\n", "\n").replaceAll("\r", "\n");
  return createHash(MODEL_HASH_ALGORITHM).update(normalized, "utf8").digest("hex");
}

function hashLiteral(stamp: string | undefined): string {
  return stamp !== undefined ? `${MODEL_HASH_ALGORITHM}:${stamp}` : UNSTAMPED;
}

interface BasePlan {
  readonly kept: readonly string[];
  readonly dropped: readonly string[];
}

/** Render a complete, importable TypeScript module for `definitions`.
 *
 * `stamp` is the {@link modelStamp} of the model source, recorded in the
 * module so a reader — and the `--check` gate — can tell what it was generated
 * from. Without one the module says `unstamped` rather than claim a hash it
 * does not have. */
export function renderModule(
  definitions: readonly Definition[],
  stamp?: string,
): string {
  const names = classNames(definitions);
  const lines: string[] = [
    GENERATED_HEADER,
    "// Typed views over SysML definitions, generated from a parsed model.",
    "",
    `import * as _t from ${literal(PACKAGE_NAME)};`,
    "",
    `export const SYSML_GENERATOR_VERSION = ${literal(GENERATOR_VERSION)};`,
    `export const SYSML_MODEL_HASH = ${literal(hashLiteral(stamp))};`,
  ];
  if (definitions.length === 0) {
    lines.push("");
    return lines.join("\n");
  }
  const plan = basePlan(definitions);
  const linearizations = plan.linearizations;
  for (const definition of dependencyOrder(definitions)) {
    lines.push("", "", ...renderClass(definition, names, plan.plan.get(definition.id), linearizations, definitions));
  }
  lines.push("");
  return lines.join("\n");
}

function basePlan(
  definitions: readonly Definition[],
): { plan: Map<string, BasePlan>; linearizations: Map<string, string[]> } {
  const generated = new Set(definitions.map((definition) => definition.id));
  const linearizations = new Map<string, string[]>();
  const plan = new Map<string, BasePlan>();
  for (const definition of dependencyOrder(definitions)) {
    const kept: string[] = [];
    const declared = [...new Set(definition.baseIds)].filter((baseId) => generated.has(baseId));
    const candidates = declared.filter((baseId) => linearizations.has(baseId));
    for (const baseId of withoutImplied(candidates, linearizations)) {
      if (linearize(definition.id, [...kept, baseId], linearizations) === undefined) {
        continue;
      }
      kept.push(baseId);
    }
    const line = linearize(definition.id, kept, linearizations) ?? [definition.id];
    linearizations.set(definition.id, line);
    const dropped = declared.filter((baseId) => !line.includes(baseId));
    plan.set(definition.id, { kept, dropped });
  }
  return { plan, linearizations };
}

function withoutImplied(bases: readonly string[], linearizations: Map<string, string[]>): string[] {
  const unique = [...new Set(bases)];
  return unique.filter(
    (baseId) =>
      !unique.some(
        (other) => other !== baseId && (linearizations.get(other) ?? []).slice(1).includes(baseId),
      ),
  );
}

function linearize(
  target: string,
  bases: readonly string[],
  linearizations: Map<string, string[]>,
): string[] | undefined {
  const sequences = bases.map((base) => [...(linearizations.get(base) ?? [base])]);
  sequences.push([...bases]);
  const result = [target];
  for (;;) {
    const remaining = sequences.filter((sequence) => sequence.length > 0);
    if (remaining.length === 0) {
      return result;
    }
    const head = remaining.find(
      (sequence) => !remaining.some((other) => other.slice(1).includes(sequence[0])),
    )?.[0];
    if (head === undefined) {
      return undefined;
    }
    result.push(head);
    for (const sequence of remaining) {
      if (sequence[0] === head) {
        sequence.shift();
      }
    }
    sequences.length = 0;
    sequences.push(...remaining);
  }
}

function dependencyOrder(definitions: readonly Definition[]): Definition[] {
  const byId = new Map(definitions.map((definition) => [definition.id, definition]));
  const ordered: Definition[] = [];
  const emitted = new Set<string>();
  const visiting = new Set<string>();
  const visit = (definition: Definition): void => {
    if (emitted.has(definition.id) || visiting.has(definition.id)) {
      return;
    }
    visiting.add(definition.id);
    for (const baseId of definition.baseIds) {
      const base = byId.get(baseId);
      if (base !== undefined) {
        visit(base);
      }
    }
    visiting.delete(definition.id);
    emitted.add(definition.id);
    ordered.push(definition);
  };
  for (const definition of definitions) {
    visit(definition);
  }
  return ordered;
}

function edgeKinds(definition: Definition): Map<string, string> {
  const edges = new Map<string, string>();
  for (const spec of definition.specializations) {
    if (GENERALIZATION_KINDS.has(spec.kind) && spec.targetId !== "") {
      edges.set(spec.targetId, spec.kind);
    }
  }
  return edges;
}

function featuresOf(line: readonly string[], definitions: readonly Definition[]): Feature[] {
  const byId = new Map(definitions.map((definition) => [definition.id, definition]));
  const seen = new Set<string>();
  const features: Feature[] = [];
  for (const id of line) {
    for (const feature of byId.get(id)?.features ?? []) {
      if (!seen.has(feature.name)) {
        seen.add(feature.name);
        features.push(feature);
      }
    }
  }
  return features;
}

function renderClass(
  definition: Definition,
  names: Map<string, string>,
  plan: BasePlan | undefined,
  linearizations: Map<string, string[]>,
  definitions: readonly Definition[],
): string[] {
  const kept = plan?.kept ?? definition.baseIds;
  const dropped = plan?.dropped ?? [];
  const bases = kept.filter((baseId) => names.has(baseId)).map((baseId) => names.get(baseId) ?? "");
  const unmapped = definition.baseIds.filter((baseId) => !names.has(baseId));
  const edges = edgeKinds(definition);
  const header = `export class ${names.get(definition.id) ?? identifier(definition.name)} extends ${bases[0] ?? "_t.TypedObject"} {`;

  const lines = [
    `/** ${definition.kind} ${definition.id}. */`,
    header,
    ...unmapped.map(
      (baseId) => `  // ${edges.get(baseId) ?? "specializes"} ${baseId}, which has no generated class`,
    ),
    ...dropped.map(
      (baseId) =>
        `  // ${edges.get(baseId) ?? "specializes"} ${baseId}, left out: ` +
        "the generated hierarchy cannot linearize it with the bases above",
    ),
    `  static readonly sysmlId: string = ${literal(definition.id)};`,
    "  static { _t.registerTyped(this); }",
  ];

  // TypeScript has single inheritance: the first kept base is the superclass,
  // and every other base Python would have carried is re-declared as getters,
  // so every feature its class exposes is reachable here.
  const inheritedFeatures = new Map<string, Feature>();
  const ownNames = new Set(definition.features.map((feature) => feature.name));
  for (const baseId of [...kept.slice(1), ...dropped]) {
    for (const feature of featuresOf(linearizations.get(baseId) ?? [baseId], definitions)) {
      if (!ownNames.has(feature.name) && !inheritedFeatures.has(feature.name)) {
        inheritedFeatures.set(feature.name, feature);
      }
    }
  }

  for (const feature of [...definition.features, ...inheritedFeatures.values()]) {
    lines.push("", ...renderGetter(feature, names));
  }
  lines.push("}");
  return lines;
}

function renderGetter(feature: Feature, names: Map<string, string>): string[] {
  const tsType = featureType(feature, names);
  const ident = propertyName(feature.name);
  let doc = `${feature.kind} ${feature.id}.`;
  if (RESERVED_MEMBERS.has(identifier(feature.name))) {
    doc += ` Renamed from ${JSON.stringify(feature.name)}, which TypedObject already defines.`;
  }
  if (tsType.comment !== "") {
    doc += ` Mapped to ${tsType.annotation}: ${tsType.comment}.`;
  }
  return [
    `  /** ${doc} */`,
    `  get ${ident}(): ${tsType.annotation} {`,
    `    return ${accessor(feature)}(this, ${literal(feature.name)}, ${tsType.decoder});`,
    "  }",
  ];
}

/** Render the typed module for a loaded model.
 *
 * `sourceText` is the model source the module is stamped with; it is required
 * so a module cannot silently claim the hash of nothing. A model of several
 * documents (`Connection.parseSources`) is generated whole, from every
 * document's root. */
export async function generateSource(model: Model, sourceText: string): Promise<string> {
  return renderModule(await collectDefinitions(...model.roots), modelStamp(sourceText));
}

