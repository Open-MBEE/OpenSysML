  "cached binary at ~/.opensysml/bin/sysml-grpc and set $OPENSYSML_GRPC_VERSION to a " +
  "release that has it. Generating against a service without type facts would emit " +
  "a module in which every feature is typed `SysMLValue`, indistinguishable from a " +
  "feature that is genuinely untyped, so generation stops instead.";

/** Fail unless `connection`'s service can supply static type facts. */
export function requireTypeFacts(connection: Connection): void {
  requireCapability(connection.info, CAPABILITY_TYPE_FACTS, TYPE_FACTS_REMEDY);
}

interface GenerateArgs {
  source: string;
  output?: string | undefined;
  host: string;
  port?: number | undefined;
  check: boolean;
}

/** The externally managed service `--host`/`--port` names, or undefined when
 * neither names one and the connection starts a private child — or honors
 * $OPENSYSML_SERVICE — the way `connect()` does with no address. */
export function serviceAddress(host: string, port?: number): string | undefined {
  if (port === undefined && host === "localhost") {
    return undefined;
  }
  return splitTarget(host, port);
}

function splitTarget(host: string, port: number | undefined): string {
  const fallback = (): string => `${host}:${port ?? 50051}`;
  if (!host.includes(":")) {
    return fallback();
  }
  let name: string;
  let written: string;
  if (host.startsWith("[")) {
    const closing = host.indexOf("]");
    if (closing === -1 || !host.slice(closing + 1).startsWith(":")) {
      return fallback();
    }
    name = host.slice(0, closing + 1);
    written = host.slice(closing + 2);
  } else if (host.indexOf(":") !== host.lastIndexOf(":")) {
    return fallback();
  } else {
    const parts = host.split(":");
    name = parts[0] ?? "";
    written = parts[1] ?? "";
  }
  if (!/^\d+$/.test(written)) {
    throw new RangeError(
      `host=${JSON.stringify(host)} names no port this client can read; pass ` +
        `host and port separately, as --host ${JSON.stringify(name)} --port <port>`,
    );
  }
  const embedded = Number.parseInt(written, 10);
  if (port !== undefined && port !== embedded) {
    throw new RangeError(
      `host=${JSON.stringify(host)} and port=${port} name different ports; give the port once`,
    );
  }
  return `${name}:${String(embedded)}`;
}

function parseArgs(argv: readonly string[]): GenerateArgs | { error: string; code: number } {
  const args: Partial<GenerateArgs> = { host: "localhost", check: false };
  const rest: string[] = [];
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "-o" || arg === "--output") {
      args.output = argv[++index];
    } else if (arg.startsWith("--output=")) {
      args.output = arg.slice("--output=".length);
    } else if (arg === "--host") {
      args.host = argv[++index];
    } else if (arg.startsWith("--host=")) {
      args.host = arg.slice("--host=".length);
    } else if (arg === "--port") {
      args.port = Number.parseInt(argv[++index], 10);
    } else if (arg.startsWith("--port=")) {
      args.port = Number.parseInt(arg.slice("--port=".length), 10);
    } else if (arg === "--check") {
      args.check = true;
    } else if (arg === "-h" || arg === "--help") {
      return { error: help(), code: 0 };
    } else {
      rest.push(arg);
    }
  }
  if (args.output === "" || args.host === "" || Number.isNaN(args.port)) {
    return { error: "error: an option is missing its value or is invalid", code: 2 };
  }
  if (rest.length !== 1) {
    return { error: "error: expected exactly one source path", code: 2 };
  }
  return { source: rest[0], output: args.output, host: args.host ?? "localhost", port: args.port, check: args.check ?? false };
}

function help(): string {
  return [
    "usage: opensysml-generate [-h] [-o OUTPUT] [--host HOST] [--port PORT] [--check] source",
    "",
    "Generate typed TypeScript classes from a SysML model.",
    "",
    "positional arguments:",
    "  source         path to a .sysml file",
    "",
    "options:",
    "  -h, --help     show this help message and exit",
    "  -o, --output   output .ts path (default: stdout)",
    "  --host HOST    sysml-grpc host (default: localhost)",
    "  --port PORT    sysml-grpc port (default: 50051)",
    "  --check        do not write; exit non-zero if regenerating would change --output",
  ].join("\n");
}

/** Entry point for the `opensysml-generate` bin. */
export async function main(argv: readonly string[] = process.argv.slice(2)): Promise<number> {
  const parsed = parseArgs(argv);
  if ("error" in parsed) {
    const out = parsed.code === 0 ? console.log : console.error;
    out(parsed.error);
    return parsed.code;
  }
  if (parsed.check && parsed.output === undefined) {
    console.error("error: --check requires -o/--output");
    return 2;
  }
  let sourceText: string;
  try {
    sourceText = readFileSync(parsed.source, "utf8");
  } catch (error) {
    console.error(`error: cannot read ${parsed.source}: ${(error as Error).message}`);
    return 2;
  }

  let address: string | undefined;
  try {
    address = serviceAddress(parsed.host, parsed.port);
  } catch (error) {
    console.error(`error: ${(error as Error).message}`);
    return 2;
  }
  let connection;
  try {
    connection = address === undefined ? await connect() : await connect({ address });
  } catch (error) {
    console.error(`error: ${(error as Error).message}`);
    return 2;
  }

  try {
    const model = await connection.load(parsed.source);

    try {
      requireTypeFacts(connection);
    } catch (error) {
      if (error instanceof MissingCapabilityError) {
        console.error(`error: ${error.message}`);
        return 1;
      }
      throw error;
    }

    const errors = model.errors;
    if (errors.length > 0) {
      for (const diagnostic of errors) {
        console.error(`error: ${diagnostic.message}`);
      }
      return 1;
    }

    const source = await generateSource(model, sourceText);

    const output = parsed.output;
    if (parsed.check) {
      let existing: string | undefined;
      try {
        existing = readFileSync(output as string, "utf8");
      } catch {
        existing = undefined;
      }
      if (existing === source) {
        return 0;
      }
      const reason = existing === undefined ? "does not exist" : "is out of date";
      console.error(
        `error: ${output as string} ${reason}; regenerate with: ` +
          `opensysml-generate ${parsed.source} -o ${output as string}`,
      );
      return 1;
    }

    if (parsed.output !== undefined) {
      writeFileSync(parsed.output, source, "utf8");
    } else {
      process.stdout.write(source);
    }
    return 0;
  } finally {
    await connection.close();
  }
}
