struct HelperTyped <: TypedObject
    instance::Instance
end
struct HelperChild <: TypedObject
    instance::Instance
end
OpenSysML._register_typed!(HelperTyped, "P::Base")
OpenSysML._register_typed!(HelperChild, "P::Child", ["P::Base"])

@testset "typed value helpers" begin

    child = Instance(2, "P::Child", Dict{String,Any}())
    instance = Instance(1, "P::Child", Dict{String,Any}(
        "bool" => true,
        "int" => Int64(7),
        "float" => 3,
        "complex" => 2.0,
        "string" => "value",
        "quantity" => Quantity(1, "m"),
        "enum" => EnumLiteral("P::E::x", "P::E", "x", nothing),
        "child" => child,
        "optional_empty" => Unset(),
        "optional_many" => [1, 2],
        "items" => [1, 2],
        "nothing" => nothing,
    ))
    typed = from_instance(HelperTyped, instance)
    @test as_bool("bool", true) === true
    @test as_int("int", 7) == 7
    @test as_float("float", 3) === 3.0
    @test as_complex("complex", 2) === ComplexF64(2)
    @test as_str("string", "value") == "value"
    @test as_quantity("quantity", Quantity(1, "m")) == Quantity(1, "m")
    @test as_enum_literal("enum", instance.enum) == instance.enum
    @test as_object("anything", :value) === :value
    @test as_typed(HelperChild)("child", child) isa HelperChild
    @test feature_value(typed, "bool", as_bool) === true
    @test optional_feature_value(typed, "optional_empty", as_int) === nothing
    @test optional_feature_value(typed, "missing", as_int) === nothing
    @test_throws TypeMismatchError optional_feature_value(typed, "optional_many", as_int)
    @test list_feature_value(typed, "items", as_int, Int64) == Int64[1, 2]
    @test list_feature_value(typed, "missing", as_int, Int64) == Int64[]
    @test list_feature_value(typed, "nothing", as_int, Int64) == Int64[]
    @test from_instance(HelperTyped, instance) isa HelperTyped
    @test_throws InstanceTypeError from_instance(HelperChild,
        Instance(3, "P::Base", Dict{String,Any}()))
    @test unchecked(HelperChild, instance) isa HelperChild
    @test_throws TypeMismatchError as_bool("bool", 1)
    @test_throws TypeMismatchError as_int("int", true)
    @test_throws TypeMismatchError as_float("float", true)
    @test_throws TypeMismatchError as_complex("complex", true)
    @test_throws TypeMismatchError as_str("string", 1)
    @test_throws TypeMismatchError as_quantity("quantity", 1)
    @test_throws TypeMismatchError as_enum_literal("enum", 1)
    @test_throws TypeMismatchError as_typed(HelperChild)("child", 1)
end

@testset "generated typed source" begin
    if !isfile(GRPC_BINARY)
        @test_skip false
    else
        conn = private(binary=GRPC_BINARY)
        try
            path = joinpath(FIXTURES, "simple_part.sysml")
            source_text = read(path, String)
            model = parse_file(conn, path)
            generated = generate_source(model, source_text)
            @test startswith(generated, "# Generated by OpenSysML.generate_source. Do not edit.")
            @test occursin("module GeneratedModel", generated)
            @test occursin("import OpenSysML", generated)
            @test occursin("const SYSML_GENERATOR_VERSION = \"4\"", generated)
            @test occursin("const SYSML_MODEL_HASH = \"sha256:", generated)
            @test occursin("struct SimplePart <: OpenSysML.TypedObject", generated)
            @test occursin("function feature_SimplePart_mass(obj::SimplePart)::Int64", generated)
            @test !occursin("using OpenSysML", generated)

            generated_module = Module(:GeneratedTypedFixture)
            Base.include_string(generated_module, generated, "generated_fixture.jl")
            instance = instantiate(model, "Test::SimplePart")
            typed = OpenSysML.from_instance(generated_module.GeneratedModel.SimplePart, instance)
            @test generated_module.GeneratedModel.feature_SimplePart_mass(typed) == 100
            normalized = replace(replace(source_text, "\r\n" => "\n"), "\r" => "\n")
            @test generated_module.GeneratedModel.SYSML_MODEL_HASH ==
                  "sha256:" * bytes2hex(SHA.sha256(codeunits(normalized)))
        finally
            close(conn)
        end
    end
end
