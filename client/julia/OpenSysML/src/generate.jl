const GENERATED_HEADER = "# Generated by OpenSysML.generate_source. Do not edit."
const GENERATOR_VERSION = "4"
const MODEL_HASH_ALGORITHM = "sha256"
const UNSTAMPED = "unstamped"
const FEATURE_KINDS = Set((
    "attributeusage", "referenceusage", "partusage", "itemusage",
    "occurrenceusage", "individualusage", "portusage", "enumusage",
))
const GENERALIZATION_KINDS = Set(("specializes", "subsets", "redefines"))
const PRIMITIVE_GENERATION_TYPES = Dict(
    "Boolean" => ("Bool", "OpenSysML.as_bool"),
    "String" => ("String", "OpenSysML.as_str"),
    "Natural" => ("Int64", "OpenSysML.as_int"),
    "Integer" => ("Int64", "OpenSysML.as_int"),
    "Rational" => ("Float64", "OpenSysML.as_float"),
    "Real" => ("Float64", "OpenSysML.as_float"),
    "Complex" => ("ComplexF64", "OpenSysML.as_complex"),
)
const JULIA_RESERVED_IDENTIFIERS = Set((
    "baremodule", "begin", "break", "catch", "const", "continue", "do", "else",
    "elseif", "end", "export", "false", "finally", "for", "function", "global",
    "if", "import", "let", "local", "macro", "module", "mutable", "primitive",
    "quote", "return", "struct", "true", "try", "using", "where", "while",
    "GeneratedModel", "OpenSysML", "SYSML_GENERATOR_VERSION", "SYSML_MODEL_HASH",
))

struct _GeneratedDefinition
    facts::SymbolFacts
    features::Vector{SymbolFacts}
end

function _definition_kind(kind)
    lowered = lowercase(String(kind))
    endswith(lowered, "def") || lowered == "metaclass"
end

function _collect_generation_facts!(info::SymbolInfo, found, facts_by_id)
    child_symbols = children(info)
    info_facts = facts(info)
    facts_by_id[info_facts.id] = info_facts
    if _definition_kind(info.kind)
        features = SymbolFacts[facts(child) for child in child_symbols
                               if lowercase(child.kind) in FEATURE_KINDS]
        sort!(features; by=feature -> feature.id)
        push!(found, _GeneratedDefinition(info_facts, features))
    end
    for child in child_symbols
        _collect_generation_facts!(child, found, facts_by_id)
    end
end

function _names_type(type_facts)
    type_facts !== nothing &&
        (!isempty(type_facts.resolved_id) || !isempty(type_facts.declared))
end

function _inherited_fact(facts::SymbolFacts, facts_by_id, choose; depth=0)
    depth >= 16 && return nothing
    for specialization in facts.specializations
        specialization.kind in GENERALIZATION_KINDS || continue
        isempty(specialization.target_id) && continue
        parent = get(facts_by_id, specialization.target_id, nothing)
        parent === nothing && continue
        candidate = choose(parent)
        candidate === nothing || return candidate
        candidate = _inherited_fact(parent, facts_by_id, choose; depth=depth + 1)
        candidate === nothing || return candidate
    end
    nothing
end

function _resolved_feature_facts(facts::SymbolFacts, facts_by_id)
    type_facts = facts.type
    if !_names_type(type_facts)
        inherited = _inherited_fact(facts, facts_by_id,
            parent -> _names_type(parent.type) ? parent.type : nothing)
        if inherited !== nothing
            own = type_facts
            type_facts = TypeFacts(
                inherited.declared, inherited.resolved_id, inherited.resolved_kind,
                own === nothing || isempty(own.primitive) ? inherited.primitive : own.primitive,
                own === nothing || isempty(own.primitive_source) ?
                    inherited.primitive_source : own.primitive_source,
                (own !== nothing && own.quantity) || inherited.quantity,
                own === nothing || isempty(own.unit) ? inherited.unit : own.unit,
            )
        end
    end
    multiplicity = facts.multiplicity
    multiplicity === nothing &&
        (multiplicity = _inherited_fact(facts, facts_by_id, parent -> parent.multiplicity))
    SymbolFacts(facts.id, facts.name, facts.kind, type_facts, multiplicity,
        facts.specializations, facts.attributes, facts.withheld_library_attributes)
end

function _collect_definitions(model::Model)
    require_capability(model.connection, CAPABILITY_TYPE_FACTS)
    definitions = _GeneratedDefinition[]
    facts_by_id = Dict{String,SymbolFacts}()
    for root_symbol in model.roots
        _collect_generation_facts!(root_symbol, definitions, facts_by_id)
    end
    resolved = _GeneratedDefinition[
        _GeneratedDefinition(definition.facts,
            SymbolFacts[_resolved_feature_facts(feature, facts_by_id)
                        for feature in definition.features])
        for definition in definitions
    ]
    sort!(resolved; by=definition -> definition.facts.id)
end

function _identifier(name::AbstractString)
    io = IOBuffer()
    first_char = true
    for character in String(name)
        valid = character == '_' || isletter(character) ||
                (!first_char && isnumeric(character))
        print(io, valid ? character : '_')
        first_char = false
    end
    identifier = String(take!(io))
    isempty(identifier) && (identifier = "_")
    isdigit(first(identifier)) && (identifier = "_" * identifier)
    identifier in JULIA_RESERVED_IDENTIFIERS && (identifier *= "_")
    identifier
end

function _class_names(definitions)
    groups = Dict{String,Vector{_GeneratedDefinition}}()
    for definition in definitions
        push!(get!(groups, _identifier(definition.facts.name), _GeneratedDefinition[]), definition)
    end
    names = Dict{String,String}()
    for (simple, group) in groups
        if length(group) == 1
            names[first(group).facts.id] = simple
        else
            for definition in group
                names[definition.facts.id] =
                    join(_identifier.(split(definition.facts.id, "::")), "_")
            end
        end
    end
    used = Set{String}()
    for definition in definitions
        id = definition.facts.id
        base = names[id]
        name = base
        suffix = 2
        while name in used
            name = "$(base)_$(suffix)"
            suffix += 1
        end
        names[id] = name
        push!(used, name)
    end
    names
end

function _feature_function_names(definition, class_name)
    output = Dict{String,String}()
    used = Set{String}()
    for feature in definition.features
        base = "feature_" * class_name * "_" * _identifier(feature.name)
        name = base
        suffix = 2
        while name in used
            name = "$(base)_$(suffix)"
            suffix += 1
        end
        output[feature.id] = name
        push!(used, name)
    end
    output
end

function _type_mapping(facts::SymbolFacts, names)
    type_facts = facts.type
    type_facts === nothing && return ("Any", "OpenSysML.as_object")
    if type_facts.quantity && !isempty(type_facts.unit)
        return ("OpenSysML.Quantity", "OpenSysML.as_quantity")
    elseif type_facts.quantity
        return ("Any", "OpenSysML.as_object")
    end
    mapped = get(PRIMITIVE_GENERATION_TYPES, type_facts.primitive, nothing)
    mapped === nothing || return mapped
    lowercase(type_facts.resolved_kind) == "enumdef" &&
        return ("OpenSysML.EnumLiteral", "OpenSysML.as_enum_literal")
    if haskey(names, type_facts.resolved_id)
        class_name = names[type_facts.resolved_id]
        return (class_name, "OpenSysML.as_typed($(class_name))")
    end
    ("Any", "OpenSysML.as_object")
end

function _feature_signature(facts::SymbolFacts, names)
    element_type, decoder = _type_mapping(facts, names)
    multiplicity = facts.multiplicity
    if multiplicity !== nothing && is_collection(multiplicity) === true
        return ("Vector{$(element_type)}", decoder, :list, element_type)
    elseif multiplicity !== nothing && is_optional(multiplicity) === true
        return ("Union{Nothing,$(element_type)}", decoder, :optional, element_type)
    end
    (element_type, decoder, :required, element_type)
end

_julia_literal(value) = JSON.json(String(value))

function _model_stamp(source_text::AbstractString)
    normalized = replace(replace(String(source_text), "\r\n" => "\n"), "\r" => "\n")
    bytes2hex(sha256(codeunits(normalized)))
end

function _render_generated_module(definitions, stamp)
    names = _class_names(definitions)
    exports = String[]
    lines = String[
        GENERATED_HEADER,
        "module GeneratedModel",
        "import OpenSysML",
        "const SYSML_GENERATOR_VERSION = $(_julia_literal(GENERATOR_VERSION))",
        "const SYSML_MODEL_HASH = $(_julia_literal(MODEL_HASH_ALGORITHM * ":" * stamp))",
    ]
    isempty(definitions) || push!(lines, "")
    for definition in definitions
        name = names[definition.facts.id]
        push!(lines, "struct $(name) <: OpenSysML.TypedObject")
        push!(lines, "    instance::OpenSysML.Instance")
        push!(lines, "end")
        bases = unique(String[s.target_id for s in definition.facts.specializations
                              if s.kind in GENERALIZATION_KINDS &&
                                 haskey(names, s.target_id)])
        push!(lines, "OpenSysML._register_typed!($(name), $(_julia_literal(definition.facts.id)), " *
                     "$(JSON.json(bases)))")
        push!(exports, name)
        function_names = _feature_function_names(definition, name)
        for feature in definition.features
            function_name = function_names[feature.id]
            result_type, decoder, cardinality, element_type =
                _feature_signature(feature, names)
            push!(lines, "function $(function_name)(obj::$(name))::$(result_type)")
            if cardinality === :list
                push!(lines, "    OpenSysML.list_feature_value(obj, $(_julia_literal(feature.name)), " *
                             "$(decoder), $(element_type))")
            elseif cardinality === :optional
                push!(lines, "    OpenSysML.optional_feature_value(obj, $(_julia_literal(feature.name)), $(decoder))")
            else
                push!(lines, "    OpenSysML.feature_value(obj, $(_julia_literal(feature.name)), $(decoder))")
            end
            push!(lines, "end")
            push!(exports, function_name)
        end
        push!(lines, "")
    end
    isempty(exports) || push!(lines, "export " * join(unique(exports), ", "))
    push!(lines, "end")
    join(lines, "\n") * "\n"
end

"""Generate a typed Julia module for a loaded model and its source text."""
function generate_source(model::Model, source_text::AbstractString)::String
    definitions = _collect_definitions(model)
    _render_generated_module(definitions, _model_stamp(source_text))
end

function generate_main(args=ARGS)
    source_path = nothing
    output_path = nothing
    host = "localhost"
    port = "50051"
    explicit_port = false
    check = false
    values = String[String(arg) for arg in args]
    i = 1
    while i <= length(values)
        arg = values[i]
        if arg in ("-o", "--output", "--host", "--port")
            i < length(values) || return _generation_usage_error("$(arg) requires a value")
            i += 1
            value = values[i]
            arg in ("-o", "--output") ? (output_path = value) :
            arg == "--host" ? (host = value) : (port = value; explicit_port = true)
        elseif startswith(arg, "--output=")
            output_path = arg[length("--output=")+1:end]
        elseif startswith(arg, "--host=")
            host = arg[length("--host=")+1:end]
        elseif startswith(arg, "--port=")
            port = arg[length("--port=")+1:end]
            explicit_port = true
        elseif arg == "--check"
            check = true
        elseif startswith(arg, "-")
            return _generation_usage_error("unknown option $(arg)")
        elseif source_path === nothing
            source_path = arg
        else
            return _generation_usage_error("unexpected argument $(arg)")
        end
        i += 1
    end
    source_path === nothing && return _generation_usage_error("a SysML source path is required")
    check && output_path === nothing &&
        return _generation_usage_error("--check requires -o/--output")
    source_text = try
        read(source_path, String)
    catch err
        println(stderr, "error: cannot read $(source_path): $(sprint(showerror, err))")
        return 2
    end
    address = explicit_port || occursin(":", host) ? host : "$(host):$(port)"
    explicit_port && (address = "$(host):$(port)")
    connection = try
        external(address)
    catch err
        println(stderr, "error: $(sprint(showerror, err))")
        return 2
    end
    generated = try
        model = parse_file(connection, source_path)
        for diagnostic in errors(model)
            println(stderr, "error: $(diagnostic.message)")
        end
        isok(model) || return 1
        generate_source(model, source_text)
    catch err
        println(stderr, "error: $(sprint(showerror, err))")
        return 1
    finally
        close(connection)
    end
    if check
        existing = isfile(output_path) ? read(output_path, String) : nothing
        existing == generated && return 0
        reason = existing === nothing ? "does not exist" : "is out of date"
        println(stderr, "error: $(output_path) $(reason); regenerate with generate_main")
        return 1
    elseif output_path === nothing
        print(generated)
    else
        try
            write(output_path, generated)
        catch err
            println(stderr, "error: cannot write $(output_path): $(sprint(showerror, err))")
            return 2
        end
    end
    0
end

_generation_usage_error(message) = begin
    println(stderr, "error: $(message)")
    2
end
