using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace OpenMBEE.OpenSysML.Generate;

/// <summary>
/// Writes a <see cref="GenerationPlan"/> as one C# file. Nothing in it depends on the machine, the time or the
/// service it was read through: every type is spelled from <c>global::</c>, and declarations follow the plan's
/// ordinal order, so the same model always gives the same bytes.
/// </summary>
internal static class Emitter
{
    /// <summary>The emission schema: bumped whenever the file generated from an unchanged model would change.</summary>
    internal const string GeneratorVersion = "2";

    private const string Client = "global::OpenMBEE.OpenSysML";
    private const string Typed = Client + ".Typed";
    private const string Instance = Client + ".Instance";
    private const string Instantiation = Client + ".Instantiation";

    /// <summary>The file, with <c>\n</c> line endings.</summary>
    internal static string Render(GenerationPlan plan)
    {
        var writer = new Writer();
        writer.Line("// <auto-generated>");
        writer.Line("//     Generated by OpenMBEE.OpenSysML.Generate from a SysML model. Do not edit it: regenerate it");
        writer.Line("//     from the same documents, and check that it is current with --check.");
        foreach (var document in plan.Documents)
        {
            writer.Line($"//     Document: {document}");
        }

        writer.Line("// </auto-generated>");
        writer.Line();
        writer.Line("#nullable enable");

        var byNamespace = plan.Definitions.GroupBy(definition => definition.Namespace, StringComparer.Ordinal).ToDictionary(group => group.Key, group => group.ToList(), StringComparer.Ordinal);
        writer.Line();
        writer.Open($"namespace {plan.RootNamespace}");
        Registry(writer, plan);
        foreach (var definition in byNamespace.GetValueOrDefault(plan.RootNamespace) ?? [])
        {
            writer.Line();
            Definition(writer, plan, definition);
        }

        writer.Close();
        foreach (var (name, definitions) in byNamespace.Where(entry => entry.Key != plan.RootNamespace).OrderBy(entry => entry.Key, StringComparer.Ordinal))
        {
            writer.Line();
            writer.Open($"namespace {name}");
            for (var i = 0; i < definitions.Count; i++)
            {
                if (i > 0)
                {
                    writer.Line();
                }

                Definition(writer, plan, definitions[i]);
            }

            writer.Close();
        }

        return writer.ToString();
    }

    private static void Registry(Writer writer, GenerationPlan plan)
    {
        writer.Line("/// <summary>What this file was generated from, and the registry every typed view in it is resolved through.</summary>");
        writer.Open($"public static class {Planner.RegistryName}");
        writer.Line("/// <summary>The emission schema of OpenMBEE.OpenSysML.Generate this file was generated with.</summary>");
        writer.Line($"public const string GeneratorVersion = {Identifiers.Literal(GeneratorVersion)};");
        writer.Line();
        writer.Line("/// <summary>The stamp of the model documents this file was generated from: a SHA-256 digest of their names and exact bytes.</summary>");
        writer.Line($"public const string ModelHash = {Identifiers.Literal(plan.ModelHash)};");
        writer.Line();
        writer.Line("/// <summary>");
        writer.Line("/// Every generated class, by the qualified name of the SysML definition it was generated from, and the");
        writer.Line("/// definition each usage is typed by.");
        writer.Line("/// </summary>");
        writer.Line($"public static {Typed}.TypedRegistry Registry {{ get; }} = new {Typed}.TypedRegistry(");
        writer.Indent();
        writer.Line($"new global::System.Collections.Generic.KeyValuePair<string, {Typed}.TypedFactory>[]");
        writer.Open();
        foreach (var definition in plan.Definitions.OrderBy(definition => definition.Id, StringComparer.Ordinal))
        {
            writer.Line($"new({Identifiers.Literal(definition.Id)}, static (instance, instantiation) => new {definition.ClassReference}(instance, instantiation)),");
        }

        writer.Close(",");
        writer.Line("new global::System.Collections.Generic.KeyValuePair<string, string>[]");
        writer.Open();
        foreach (var (usage, definition) in plan.UsageTypes)
        {
            writer.Line($"new({Identifiers.Literal(usage)}, {Identifiers.Literal(definition.Id)}),");
        }

        writer.Close(");");
        writer.Outdent();
        writer.Close();
    }

    private static void Definition(Writer writer, GenerationPlan plan, DefinitionPlan definition)
    {
        var described = Identifiers.DocText($"{definition.Symbol.Kind} {definition.Id}");
        writer.Line($"/// <summary>{described}.</summary>");
        var remarks = definition.UngeneratedBases
            .Select(edge => $"Also {edge.Kind} {edge.TargetId}, which has no generated class.")
            .ToList();
        if (definition.UnnamedFeatures > 0)
        {
            remarks.Add(string.Create(CultureInfo.InvariantCulture, $"Its {definition.UnnamedFeatures} unnamed feature{(definition.UnnamedFeatures == 1 ? " has" : "s have")} no property, which reads a feature by its name."));
        }

        Remarks(writer, remarks);
        var interfaceBases = definition.Bases.Count == 0
            ? $"{Typed}.ITypedObject"
            : string.Join(", ", definition.Bases.Select(other => other.InterfaceReference));
        writer.Open($"public interface {definition.InterfaceName} : {interfaceBases}");
        for (var i = 0; i < definition.Features.Count; i++)
        {
            if (i > 0)
            {
                writer.Line();
            }

            var feature = definition.Features[i];
            writer.Line($"/// <summary>{Identifiers.DocText($"{feature.Symbol.Kind} {feature.Id}")}.</summary>");
            Remarks(writer, FeatureRemarks(feature));
            writer.Line($"{(feature.Hides ? "new " : string.Empty)}{PropertyType(feature.Shape)} {feature.Member} {{ get; }}");
        }

        writer.Close();
        writer.Line();

        var hides = definition.BaseClass is null ? string.Empty : "new ";
        var self = definition.InterfaceReference;
        writer.Line($"/// <summary>The generated class of {described}, a view of an instance through <c>{Identifiers.DocText(Unescaped(definition.InterfaceName))}</c>.</summary>");
        writer.Open($"public class {definition.TypeName} : {definition.BaseClass?.ClassReference ?? $"{Typed}.TypedObject"}, {self}");
        writer.Line("/// <summary>The qualified name of the SysML definition this class was generated from.</summary>");
        writer.Line($"public {hides}const string SysmlId = {Identifiers.Literal(definition.Id)};");
        writer.Line();
        writer.Line($"internal {definition.TypeName}({Instance} instance, {Instantiation}? instantiation)");
        writer.Line("    : base(instance, instantiation)");
        writer.Open();
        writer.Close();
        writer.Line();
        writer.Line($"/// <summary>A view of an instance as {Identifiers.DocText(definition.Id)}: of its own type's generated class, which a specialization's implements too.</summary>");
        writer.Line("/// <param name=\"instance\">The instance to view.</param>");
        writer.Line("/// <param name=\"instantiation\">The instantiation that built it, which nested objects are resolved through; null when there is none.</param>");
        writer.Line("/// <returns>The view.</returns>");
        writer.Line($"/// <exception cref=\"{Client}.InstanceTypeException\">Another generated class, not of a specialization of this definition, describes the instance's type.</exception>");
        writer.Line($"public static {hides}{self} FromInstance({Instance} instance, {Instantiation}? instantiation = null) =>");
        writer.Line($"    global::{plan.RootNamespace}.{Planner.RegistryName}.Registry.FromInstance<{self}>(instance, instantiation, SysmlId);");
        writer.Line();
        writer.Line($"/// <summary>A view of the object an instantiation built as {Identifiers.DocText(definition.Id)}.</summary>");
        writer.Line("/// <param name=\"instantiation\">The instantiation, whose root is viewed.</param>");
        writer.Line("/// <returns>The view.</returns>");
        writer.Line($"/// <exception cref=\"{Client}.InstanceTypeException\">Another generated class, not of a specialization of this definition, describes the root's type.</exception>");
        writer.Line($"public static {hides}{self} FromInstance({Instantiation} instantiation)");
        writer.Open();
        writer.Line("global::System.ArgumentNullException.ThrowIfNull(instantiation);");
        writer.Line("return FromInstance(instantiation.Root, instantiation);");
        writer.Close();
        writer.Line();
        writer.Line($"/// <summary>A view of an instance as {Identifiers.DocText(definition.Id)}, whatever type it reports; its properties still check what they read.</summary>");
        writer.Line("/// <param name=\"instance\">The instance to view.</param>");
        writer.Line("/// <param name=\"instantiation\">The instantiation that built it, which nested objects are resolved through; null when there is none.</param>");
        writer.Line("/// <returns>The view.</returns>");
        writer.Line($"public static {hides}{self} Unchecked({Instance} instance, {Instantiation}? instantiation = null) =>");
        writer.Line($"    new {definition.ClassReference}(instance, instantiation);");
        foreach (var implementation in definition.Implementations)
        {
            var feature = implementation.Feature;
            writer.Line();
            writer.Line($"{PropertyType(feature.Shape)} {feature.Owner.InterfaceReference}.{feature.Member} =>");
            writer.Line($"    {Typed}.TypedFeatures.{Accessor(feature.Shape)}(this, {Identifiers.Literal(implementation.Slot.Symbol.Name)}, {Decoder(plan, feature.Shape)});");
        }

        writer.Close();
    }

    private static List<string> FeatureRemarks(FeaturePlan feature)
    {
        var remarks = new List<string>();
        if (feature.Shape.Note is { } note)
        {
            remarks.Add(feature.Shape.Kind == ElementKind.Quantity ? $"A quantity: {note}." : $"Read as a Value: {note}.");
        }

        remarks.AddRange(feature.Symbol.Specializations
            .Where(edge => edge.Kind == "redefines" && edge.TargetId.Length > 0)
            .Select(edge => $"Redefines {edge.TargetId}."));
        return remarks;
    }

    private static void Remarks(Writer writer, List<string> remarks)
    {
        if (remarks.Count > 0)
        {
            writer.Line($"/// <remarks>{Identifiers.DocText(string.Join(" ", remarks))}</remarks>");
        }
    }

    private static string Unescaped(string identifier) => identifier.TrimStart('@');

    private static string ElementType(Shape shape) => shape.Kind switch
    {
        ElementKind.Boolean => "bool",
        ElementKind.String => "string",
        ElementKind.Integer => "global::System.Numerics.BigInteger",
        ElementKind.Rational => $"{Client}.Rational",
        ElementKind.Real => "double",
        ElementKind.Complex => "global::System.Numerics.Complex",
        ElementKind.Quantity => $"{Client}.Quantity",
        ElementKind.EnumLiteral => $"{Client}.Value.EnumLiteralValue",
        ElementKind.Generated => shape.Definition!.InterfaceReference,
        _ => $"{Client}.Value",
    };

    private static bool IsValueType(Shape shape) =>
        shape.Kind is ElementKind.Boolean or ElementKind.Integer or ElementKind.Real or ElementKind.Complex;

    private static string PropertyType(Shape shape) => shape.Cardinality switch
    {
        Cardinality.Many => $"{Client}.ValueList<{ElementType(shape)}>",
        Cardinality.Optional => $"{ElementType(shape)}?",
        _ => ElementType(shape),
    };

    private static string Accessor(Shape shape)
    {
        var name = shape.Cardinality switch
        {
            Cardinality.Many => "List",
            Cardinality.Optional => IsValueType(shape) ? "OptionalValue" : "Optional",
            _ => "Required",
        };
        return $"{name}<{ElementType(shape)}>";
    }

    private static string Decoder(GenerationPlan plan, Shape shape) => shape.Kind switch
    {
        ElementKind.Generated => $"global::{plan.RootNamespace}.{Planner.RegistryName}.Registry.Decoder<{shape.Definition!.InterfaceReference}>({shape.Definition.ClassReference}.SysmlId)",
        ElementKind.Value => $"{Typed}.FeatureDecoders.AsValue",
        _ => $"{Typed}.FeatureDecoders.As{shape.Kind}",
    };

    private sealed class Writer
    {
        private readonly StringBuilder text = new();
        private int depth;

        internal void Line(string line = "")
        {
            if (line.Length > 0)
            {
                text.Append(' ', depth * 4).Append(line);
            }

            text.Append('\n');
        }

        internal void Open(string? header = null)
        {
            if (header is not null)
            {
                Line(header);
            }

            Line("{");
            depth++;
        }

        internal void Close(string suffix = "")
        {
            depth--;
            Line("}" + suffix);
        }

        internal void Indent() => depth++;

        internal void Outdent() => depth--;

        public override string ToString() => text.ToString();
    }
}
