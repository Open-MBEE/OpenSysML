using System;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using OpenMBEE.OpenSysML.Tests;
using Xunit;

namespace OpenMBEE.OpenSysML.Generate.Tests;

/// <summary>
/// The command end to end against a live service: it writes, checks without writing, fails on a changed
/// input however far it is from the file named, and refuses a model it cannot generate soundly, a model with
/// errors and a service without static type facts, each with a message naming what is wrong.
/// </summary>
[Trait(Category.Name, Category.Integration)]
public sealed class CommandTests(LiveServices services) : IClassFixture<LiveServices>
{
    private static readonly string Fleet = Repository.PathOf("client", "python", "tests", "fixtures", "multifile");

    private static CancellationToken Token => TestContext.Current.CancellationToken;

    [Fact]
    public async Task ChecksWithoutWritingAndFailsWhenADocumentInADirectoryChanges()
    {
        using var temp = new TempDirectory();
        var models = Path.Combine(temp.Path, "multifile");
        Directory.CreateDirectory(models);
        foreach (var file in Directory.GetFiles(Fleet))
        {
            File.Copy(file, Path.Combine(models, Path.GetFileName(file)));
        }

        var output = Path.Combine(temp.Path, "FleetTypes.cs");
        var address = await services.AddressAsync();
        string[] arguments = [models, "-o", output, "--namespace", "Fleet.Model", "--address", address];

        Assert.Equal((0, string.Empty, string.Empty), await RunAsync(arguments));
        var written = await File.ReadAllTextAsync(output, Token);
        Assert.Equal((0, string.Empty, string.Empty), await RunAsync([.. arguments, "--check"]));

        // The changed file is one the named directory holds, and nothing in it changes what is generated but the stamp.
        await File.AppendAllTextAsync(Path.Combine(models, "units.kerml"), "\n", Token);
        var (code, stdout, stderr) = await RunAsync([.. arguments, "--check"]);

        Assert.Equal((1, string.Empty), (code, stdout));
        Assert.Equal(
            $"error: {output} is out of date; regenerate it with: dotnet run --project client/dotnet/src/OpenMBEE.OpenSysML.Generate -- {models} -o {output} --namespace Fleet.Model --address {address}\n",
            stderr.ReplaceLineEndings("\n"));
        Assert.Equal(written, await File.ReadAllTextAsync(output, Token));

        File.Delete(output);
        Assert.Contains($"error: {output} does not exist;", (await RunAsync([.. arguments, "--check"])).Error, StringComparison.Ordinal);
        Assert.False(File.Exists(output));

        var absentDirectory = Path.Combine(temp.Path, "absent", "Out.cs");
        var missing = await RunAsync([models, "-o", absentDirectory, "--check", "--namespace", "Fleet.Model", "--address", address]);
        Assert.Equal(GenerateCommand.Failed, missing.Code);
        Assert.Contains($"error: {absentDirectory} does not exist;", missing.Error, StringComparison.Ordinal);
        Assert.False(Directory.Exists(Path.GetDirectoryName(absentDirectory)));
    }

    [Fact]
    public async Task WritesToStandardOutputWithoutAnOutputFile()
    {
        var (code, stdout, stderr) = await RunAsync([Path.Combine(Fleet, "lib.sysml"), Path.Combine(Fleet, "units.kerml"), "--namespace", "Fleet.Model", "--address", await services.AddressAsync()]);

        Assert.Equal((0, string.Empty), (code, stderr));
        Assert.StartsWith("// <auto-generated>\n", stdout, StringComparison.Ordinal);
        Assert.Contains("//     Document: lib.sysml\n//     Document: units.kerml\n", stdout, StringComparison.Ordinal);
        Assert.Contains("namespace Fleet.Model.FleetLib\n", stdout, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ACheckReportsAnUnreadableOutputAsMisuseWithoutChangingIt()
    {
        using var temp = new TempDirectory();
        var model = temp.Write("m.sysml", "package P { part def A; }");
        var output = temp.Write("Out.cs", "original");
        var address = await services.AddressAsync();
        using (File.Open(output, FileMode.Open, FileAccess.ReadWrite, FileShare.None))
        {
            var (code, stdout, stderr) = await RunAsync([model, "-o", output, "--check", "--namespace", "P.Model", "--address", address]);

            Assert.Equal((GenerateCommand.Misused, string.Empty), (code, stdout));
            Assert.StartsWith($"error: cannot read {output}:", stderr, StringComparison.Ordinal);
        }

        Assert.Equal("original", await File.ReadAllTextAsync(output, Token));
        Assert.Empty(Directory.GetFiles(temp.Path, ".*.tmp"));
    }

    [Fact]
    public async Task AnOutputWriteFailureIsReportedAsMisuseAndLeavesNoStagingFile()
    {
        using var temp = new TempDirectory();
        var model = temp.Write("m.sysml", "package P { part def A; }");
        var output = Path.Combine(temp.Path, new string('x', 300) + ".cs");

        var (code, stdout, stderr) = await RunAsync([model, "-o", output, "--namespace", "P.Model", "--address", await services.AddressAsync()]);

        Assert.Equal((GenerateCommand.Misused, string.Empty), (code, stdout));
        Assert.StartsWith($"error: cannot write {output}:", stderr, StringComparison.Ordinal);
        Assert.Equal(["m.sysml"], Directory.GetFiles(temp.Path).Select(Path.GetFileName));
    }

    [Fact]
    public async Task ACheckDoesNotHideAFileSystemFailureAsAMissingOutput()
    {
        using var temp = new TempDirectory();
        var model = temp.Write("m.sysml", "package P { part def A; }");
        var output = Path.Combine(temp.Path, new string('x', 300) + ".cs");

        var (code, stdout, stderr) = await RunAsync([model, "-o", output, "--check", "--namespace", "P.Model", "--address", await services.AddressAsync()]);

        Assert.Equal((GenerateCommand.Misused, string.Empty), (code, stdout));
        Assert.StartsWith($"error: cannot read {output}:", stderr, StringComparison.Ordinal);
        Assert.Equal(["m.sysml"], Directory.GetFiles(temp.Path).Select(Path.GetFileName));
    }

    [Fact]
    public async Task AModelWithErrorsIsReportedByDocumentAndNothingIsWritten()
    {
        using var temp = new TempDirectory();
        var model = temp.Write("broken.sysml", "package P {\n    part def A :> Missing;\n}\n");
        var output = Path.Combine(temp.Path, "Out.cs");

        var (code, _, stderr) = await RunAsync([model, "-o", output, "--namespace", "P.Model", "--address", await services.AddressAsync()]);

        Assert.Equal(1, code);
        Assert.Contains("broken.sysml:2:", stderr, StringComparison.Ordinal);
        Assert.Contains("Missing", stderr, StringComparison.Ordinal);
        Assert.False(File.Exists(output));
    }

    [Fact]
    public async Task AModelThatCannotBeGeneratedSoundlyIsRefusedNamingTheFeatures()
    {
        using var temp = new TempDirectory();
        var model = temp.Write("ambiguous.sysml", """
            package P {
                private import ScalarValues::*;
                part def A { attribute mass : Real; }
                part def B { attribute mass : Real; }
                part def D :> A, B;
                part def E { attribute speed : Real; attribute Speed : Real; }
            }
            """);

        var (code, stdout, stderr) = await RunAsync([model, "--namespace", "P.Model", "--address", await services.AddressAsync()]);

        Assert.Equal((1, string.Empty), (code, stdout));
        Assert.Equal(
            [
                "error: P::D has the features P::A::mass and P::B::mass, different features that neither redefines the other, which would both be read as the property Mass",
                "error: P::E has the features P::E::Speed and P::E::speed, different features that neither redefines the other, which would both be read as the property Speed",
                "error: P::E::Speed and P::E::speed would both generate the property IE.Speed",
            ],
            stderr.ReplaceLineEndings("\n").TrimEnd('\n').Split('\n'));
    }

    [Theory]
    [InlineData(ClientWire.ConnectProto)]
    [InlineData(ClientWire.ConnectJson)]
    public async Task AServiceWithoutTypeFactsIsRefusedBeforeAnythingIsParsed(ClientWire wire)
    {
        using var handler = new LiveServices.Recording();
        await using var connection = await services.OpenAsync(wire, Token, withheld: Capabilities.TypeFacts, handler: handler);

        var refused = await Assert.ThrowsAsync<CapabilityException>(() => GenerateCommand.GenerateAsync(
            connection, SourceClosure.Read([Path.Combine(Fleet, "lib.sysml"), Path.Combine(Fleet, "units.kerml")]), "Fleet.Model", Token));

        Assert.Equal(Capabilities.TypeFacts, refused.Capability);
        Assert.Equal(["/sysml.SysMLService/GetServerInfo"], handler.Methods);
    }

    [Fact]
    public async Task TheCommandSaysWhyAServiceWithoutTypeFactsCannotGenerate()
    {
        var (code, stdout, stderr) = await RunAsync([Path.Combine(Fleet, "lib.sysml"), "--namespace", "Fleet.Model", "--address", await services.AddressAsync(Capabilities.TypeFacts)]);

        Assert.Equal((1, string.Empty), (code, stdout));
        Assert.Contains("type_facts", stderr, StringComparison.Ordinal);
        Assert.Contains("every property would be read as a Value", stderr, StringComparison.Ordinal);
    }

    private static async Task<(int Code, string Output, string Error)> RunAsync(string[] arguments)
    {
        using var output = new StringWriter();
        using var error = new StringWriter();
        var code = await GenerateCommand.RunAsync(arguments, output, error, Token);
        return (code, output.ToString(), error.ToString());
    }
}

/// <summary>What the command refuses before it reaches a service: a bad argument or an input it cannot read.</summary>
[Trait(Category.Name, Category.Unit)]
public sealed class CommandUsageTests
{
    [Fact]
    public async Task MisuseExitsTwoNamingTheProblemAndReachesNoService()
    {
        using var temp = new TempDirectory();
        var model = temp.Write("m.sysml", "package P;");
        var missing = Path.Combine(temp.Path, "absent", "Out.cs");

        Assert.Equal((2, "error: --namespace is required\nrun with --help for usage\n"), await RunAsync([model]));
        var nope = Path.Combine(temp.Path, "nope.sysml");
        Assert.Equal((2, $"error: {nope} does not exist\nrun with --help for usage\n"), await RunAsync([nope, "--namespace", "A"]));
        Assert.StartsWith($"error: cannot write {missing}: the directory", (await RunAsync([model, "-o", missing, "--namespace", "A"])).Error, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task AnExistingDirectoryIsNotAnOutputFile(bool check)
    {
        using var temp = new TempDirectory();
        var model = temp.Write("m.sysml", "package P;");
        var directory = Directory.CreateDirectory(Path.Combine(temp.Path, "Out.cs")).FullName;

        var (code, error) = await RunAsync([model, "-o", directory, "--namespace", "P.Model", .. check ? ["--check"] : Array.Empty<string>()]);

        Assert.Equal(GenerateCommand.Misused, code);
        Assert.StartsWith($"error: cannot {(check ? "read" : "write")} {directory}:", error, StringComparison.Ordinal);
        Assert.EndsWith("run with --help for usage\n", error, StringComparison.Ordinal);
        Assert.Empty(Directory.GetFileSystemEntries(directory));
        Assert.Empty(Directory.GetFiles(temp.Path, ".*.tmp"));
    }

    [Fact]
    public async Task AnUnreadableInputIsReportedAsMisuse()
    {
        using var temp = new TempDirectory();
        var model = temp.Write("m.sysml", "package P;");
        using var locked = File.Open(model, FileMode.Open, FileAccess.ReadWrite, FileShare.None);

        var (code, error) = await RunAsync([model, "--namespace", "P.Model"]);

        Assert.Equal(GenerateCommand.Misused, code);
        Assert.StartsWith($"error: cannot read {model}:", error, StringComparison.Ordinal);
    }

    [Fact]
    public async Task HelpPrintsTheUsage()
    {
        using var output = new StringWriter();
        using var error = new StringWriter();

        Assert.Equal(0, await GenerateCommand.RunAsync(["--help"], output, error, TestContext.Current.CancellationToken));
        Assert.StartsWith("usage: OpenMBEE.OpenSysML.Generate SOURCE... --namespace NAMESPACE", output.ToString(), StringComparison.Ordinal);
        Assert.Empty(error.ToString());
    }

    private static async Task<(int Code, string Error)> RunAsync(string[] arguments)
    {
        using var output = new StringWriter();
        using var error = new StringWriter();
        var code = await GenerateCommand.RunAsync(arguments, output, error, TestContext.Current.CancellationToken);
        Assert.Empty(output.ToString());
        return (code, error.ToString().ReplaceLineEndings("\n"));
    }
}
