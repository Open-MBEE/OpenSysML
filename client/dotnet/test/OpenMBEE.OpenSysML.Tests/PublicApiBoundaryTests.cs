using System;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;
using Google.Protobuf;
using OpenMBEE.OpenSysML.Internal;
using Xunit;

namespace OpenMBEE.OpenSysML.Tests;

/// <summary>
/// The generated protocol code is public and mutable, and stays outside the handwritten API: it
/// lives in OpenMBEE.OpenSysML.Wire alone, comes from the two committed buf files alone, and is
/// exempted from the handwritten API checks by those exact paths alone.
/// </summary>
[Trait(Category.Name, Category.Unit)]
public sealed partial class PublicApiBoundaryTests
{
    private const string WireNamespace = "OpenMBEE.OpenSysML.Wire";
    private static readonly string[] GeneratedFiles = ["src/OpenMBEE.OpenSysML/Wire/Sysml.cs", "src/OpenMBEE.OpenSysML/Wire/SysmlGrpc.cs"];

    // Every generated file of the client tree, in ordinal order: the buf output and the metamodel types.
    private static readonly string[] ExemptedFiles = ["src/OpenMBEE.OpenSysML.Metamodel/Generated.cs", .. GeneratedFiles];
    private static readonly string[] BaselineFiles = ["PublicAPI.Shipped.txt", "PublicAPI.Unshipped.txt"];
    private static readonly string Library = Repository.PathOf("client", "dotnet", "src", "OpenMBEE.OpenSysML");

    [GeneratedRegex(@"^DOTNET_GENERATED := (.+)$", RegexOptions.Multiline)]
    private static partial Regex MakeGenerated();

    [GeneratedRegex(@"^\[(?<glob>[^\]\n]+)\]\n(?<body>(?:[^\[\n].*\n)*)", RegexOptions.Multiline)]
    private static partial Regex EditorConfigSection();

    [GeneratedRegex(@"^(?<prefix>[^{]*)(?:\{(?<names>[^}]+)\}(?<suffix>.*))?$")]
    private static partial Regex BraceGlob();

    [GeneratedRegex(@"^\s*(namespace|using)\s+OpenMBEE\.OpenSysML\.Wire\s*;", RegexOptions.Multiline)]
    private static partial Regex WireDeclarationOrImport();

    [Fact]
    public void HandwrittenPublicTypesAreAllInTheApiBaseline()
    {
        var baseline = Baseline();
        var handwritten = typeof(RpcMethods).Assembly.GetExportedTypes()
            .Where(type => type.Namespace != WireNamespace)
            .Select(BaselineName)
            .ToList();

        Assert.Contains("OpenMBEE.OpenSysML.ValueList<T>", handwritten);
        Assert.All(handwritten, name => Assert.Contains(baseline, line => line == name || line.StartsWith(name + ".", StringComparison.Ordinal)));
    }

    [Fact]
    public void TheApiBaselineHoldsNoGeneratedProtocolCode()
    {
        Assert.DoesNotContain(Baseline(), line => line.Contains(WireNamespace, StringComparison.Ordinal));
    }

    [Fact]
    public void EveryPublicWireTypeIsGeneratedProtocolCode()
    {
        var wire = typeof(RpcMethods).Assembly.GetExportedTypes().Where(type => type.Namespace == WireNamespace).ToList();

        Assert.NotEmpty(wire);
        Assert.All(wire, type => Assert.True(
            typeof(IMessage).IsAssignableFrom(type)
                || type.IsEnum
                || type is { Name: "Types", IsAbstract: true, IsSealed: true }
                || type == typeof(Wire.SysmlReflection)
                || type == typeof(Wire.SysMLService)
                || type.DeclaringType == typeof(Wire.SysMLService),
            $"{type.FullName} is public in {WireNamespace} but is not generated protocol code."));
    }

    [Fact]
    public void TheGeneratedNamespaceIsTheSchemasCSharpNamespace()
    {
        Assert.Equal(WireNamespace, Wire.SysmlReflection.Descriptor.GetOptions().CsharpNamespace);
        Assert.Equal("sysml", Wire.SysmlReflection.Descriptor.Package);
    }

    [Fact]
    public void TheWireDirectoryHoldsTheTwoGeneratedFilesAlone()
    {
        var files = Directory.GetFiles(Path.Combine(Library, "Wire"), "*", SearchOption.AllDirectories)
            .Select(path => Path.GetRelativePath(Repository.PathOf("client", "dotnet"), path).Replace('\\', '/'))
            .Order(StringComparer.Ordinal);

        Assert.Equal(GeneratedFiles, files);
        Assert.All(GeneratedFiles, file => Assert.StartsWith(
            "// <auto-generated>\n//     Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
            File.ReadAllText(Repository.PathOf("client", "dotnet", file)).ReplaceLineEndings("\n"),
            StringComparison.Ordinal));
    }

    [Fact]
    public void HandwrittenSourceNeitherDeclaresNorImportsTheWireNamespace()
    {
        // Importing it would let generated Wire.Array shadow System.Array; handwritten code qualifies instead.
        var offenders = Directory.GetFiles(Library, "*.cs", SearchOption.AllDirectories)
            .Where(path => !IsUnder(path, "Wire") && !IsUnder(path, "obj") && !IsUnder(path, "bin"))
            .Where(path => WireDeclarationOrImport().IsMatch(File.ReadAllText(path)))
            .ToList();

        Assert.Empty(offenders);
    }

    [Fact]
    public void TheGeneratedExemptionsNameExactlyTheGeneratedFiles()
    {
        var make = MakeGenerated().Match(File.ReadAllText(Repository.PathOf("Makefile")));
        Assert.True(make.Success, "The Makefile declares no DOTNET_GENERATED.");
        Assert.Equal(ExemptedFiles, make.Groups[1].Value.Split(' ', StringSplitOptions.RemoveEmptyEntries).Order(StringComparer.Ordinal));

        var exemptions = EditorConfigSection().Matches(File.ReadAllText(Repository.PathOf("client", "dotnet", ".editorconfig")).ReplaceLineEndings("\n"))
            .Where(section => section.Groups["body"].Value.Contains("generated_code = true\n", StringComparison.Ordinal))
            .ToList();
        Assert.All(exemptions, section => Assert.Contains("dotnet_diagnostic.RS0016.severity = none\n", section.Groups["body"].Value, StringComparison.Ordinal));
        var exempted = exemptions.SelectMany(section =>
        {
            var glob = BraceGlob().Match(section.Groups["glob"].Value);
            return glob.Groups["names"].Success
                ? glob.Groups["names"].Value.Split(',').Select(name => $"{glob.Groups["prefix"].Value}{name}{glob.Groups["suffix"].Value}")
                : [glob.Groups["prefix"].Value];
        });
        Assert.Equal(ExemptedFiles, exempted.Order(StringComparer.Ordinal));
    }

    // A type as the baseline spells it: nested types dotted, a generic one with its parameters, as ValueList<T>.
    private static string BaselineName(Type type)
    {
        var name = type.FullName!.Replace('+', '.');
        return type.IsGenericTypeDefinition
            ? $"{name[..name.IndexOf('`', StringComparison.Ordinal)]}<{string.Join(", ", type.GetGenericArguments().Select(parameter => parameter.Name))}>"
            : name;
    }

    private static string[] Baseline() =>
        [.. BaselineFiles
            .SelectMany(file => File.ReadAllLines(Path.Combine(Library, file)))
            .Where(line => line.Length > 0 && !line.StartsWith('#'))];

    private static bool IsUnder(string path, string directory) =>
        Path.GetRelativePath(Library, path).Replace('\\', '/').StartsWith(directory + "/", StringComparison.Ordinal);
}
