function result = runRuns(model, varargin)
%RUNRUNS Run an action or a Monte Carlo case repeatedly, as sysml -runs does.
%   RESULT = RUNRUNS(MODEL, 'action', ID, 'runs', N, ...) runs the action N
%   times and tables every run; RUNRUNS(MODEL, 'analysis', ID, ...) samples a
%   Monte Carlo case and concludes it over the sample. The struct answers rows
%   (one per run), observables, distributions, outputs, verdicts, unconcluded,
%   seed, instances, diagnostics and standing. Options: action, analysis, runs,
%   seed, draws, clockStep, observe, inputs, performer, subject, arguments,
%   namedArguments, engine. The runs draw at random, so pass seed or fix the
%   draws with draws ('min', 'max' or 'average').

    options = opensysml.internal.nameValueOptions(struct('action', '', 'analysis', '', ...
        'runs', 1, 'seed', [], 'draws', '', 'clockStep', 0, 'observe', {{}}, 'inputs', struct(), ...
        'performer', '', 'subject', '', 'arguments', {{}}, 'namedArguments', struct(), ...
        'engine', ''), varargin, 'runRuns');
    capabilities = {'runs'};
    if ~isempty(options.performer), capabilities{end + 1} = 'performer'; end
    model.connection.requireAll(capabilities);
    request = struct('modelHash', model.hash, 'actionSymbolId', char(options.action), ...
        'analysisSymbolId', char(options.analysis), ...
        'inputs', opensysml.internal.encodeNamedArguments(options.inputs, model.connection, 'runRuns inputs'), ...
        'performerSymbolId', char(options.performer), 'subjectSymbolId', char(options.subject), ...
        'arguments', {opensysml.internal.encodeArguments(options.arguments, model.connection, 'runRuns arguments')}, ...
        'namedArguments', opensysml.internal.encodeNamedArguments(options.namedArguments, model.connection, 'runRuns namedArguments'), ...
        'runs', double(options.runs), 'draws', char(options.draws), 'clockStep', double(options.clockStep), ...
        'observe', {cellfun(@char, cellstr(options.observe), 'UniformOutput', false)});
    if ~isempty(options.seed), request.seed = sprintf('%d', uint64(options.seed)); end
    if ~isempty(options.engine), request.engine = char(options.engine); end
    raw = opensysml.call(model.connection, 'RunRuns', request, capabilities);
    result = opensysml.internal.decodeRuns(model, raw);
end
